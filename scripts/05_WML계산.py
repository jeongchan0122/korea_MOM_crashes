# -*- coding: utf-8 -*-
"""
5단계: 월별 패널로 WML 4개와 롱온리 4개의 월별 수익률을 계산한다.

만드는 방식 (모두 시가총액가중, 매달 말 구성 후 다음 달 1개월 보유)
- 2x3 (기본): 크기 2 x 모멘텀 3. 승자 쪽 = (소형 승자 + 대형 승자)/2, 패자 쪽 = (소형 패자 + 대형 패자)/2
- 5x5 (강건성 확인): 크기 5 x 모멘텀 5. 크기 그룹별 모멘텀 5분위의 평균 - 1분위의 평균
- 5분위 (강건성 확인): 모멘텀 5분위 - 1분위
- 10분위 (강건성 확인): 모멘텀 10분위 - 1분위
- 롱숏(WML) = 승자 쪽 - 패자 쪽, 롱온리 = 승자 쪽

분위 경계
- 크기와 모멘텀 경계는 구성 달마다 투자 대상 중 코스피 종목으로 계산하고, 코스닥 종목도 같은 경계로 바구니에 넣는다.
- Fama & French (2012)가 NYSE 기준을 쓰는 것처럼, 수가 많은 소형 종목에 경계가 좌우되지 않게 하기 위해서다.
- 전체 종목 기준은 강건성 확인으로 함께 계산해 출력하고, 저장하지 않는다.

계산 규칙
- 투자 대상: 코스피·코스닥, 거래정지·관리종목·스팩 아님, 시가총액 > 0. 금융업 포함.
- 모멘텀 점수: t-11 ~ t-1월 누적수익률, 11개월 모두 필요, 상폐 미반영 수익률 사용.
- 보유 수익률: 다음 달 상폐 반영 수익률을 구성 달 말 시가총액으로 가중 평균.
- 기간: 구성 1999-12 ~ 2026-08, 수익률 2000-01 ~ 2026-09.
- 샤프: 롱숏은 순투자금이 0원이므로 그대로 계산하고, 롱온리와 시장은 전월 말 CD 91일물 ÷ 12를 빼고 계산한다.

하지 않는 일
- 붕괴 정의, 예측 지표, 동일가중, 그림 그리기, 이전 단계 결과 수정.

실행: python scripts/05_WML계산.py   (먼저 scripts/04_월별패널.py를 실행해 두어야 함)
결과: 처리데이터/WML월별수익률.parquet, 처리데이터/WML바구니수익률.parquet
"""
