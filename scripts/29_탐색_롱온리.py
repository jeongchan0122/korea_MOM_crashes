import numpy as np
import pandas as pd

프로젝트 = Path(__file__).resolve().parent.parent
결과폴더 = 프로젝트 / "결과" / "탐색" / "롱온리"


def 불러오기(이름, 파일):
    명세 = importlib.util.spec_from_file_location(이름, Path(__file__).resolve().parent / 파일)
    모듈 = importlib.util.module_from_spec(명세)
    명세.loader.exec_module(모듈)
    return 모듈


검증코드 = 불러오기("검증", "15_검증.py")
선택코드 = 검증코드.선택코드
비용률 = 0.5


def 매매량들(새승자, 변승자, 시장비중, 보유달):
    """보유 달 m마다 네 가지 매매량. 새승자[구성달], 변승자[구성달](다음 달 동안 변한 값), 시장비중[구성달]."""
    def 차(a, b):
        모두 = a.index.union(b.index)
        return float((a.reindex(모두, fill_value=0) - b.reindex(모두, fill_value=0)).abs().sum())
    줄 = {}
    for m in 보유달:
        뒤, 앞 = str(pd.Period(m) - 1), str(pd.Period(m) - 2)
        a, b, mk = 새승자[뒤], 변승자[앞], 시장비중[뒤]
        줄[m] = {"WW": 차(a, b), "WM": 차(mk, b), "MW": 차(a, mk), "W현금": float(b.sum()), "현금W": 1.0}
    return pd.DataFrame(줄).T


def 수익(w, 승자, 시장, 매매, 현금=False):
    """w=1이면 승자, 0이면 시장(또는 현금). 총수익(%)과 틸트 수익(%)."""
    앞 = w.shift(1).fillna(1.0)
    if 현금:
        회전 = np.select([(앞 == 1) & (w == 1), (앞 == 1) & (w == 0), (앞 == 0) & (w == 1)],
                       [매매["WW"], 매매["W현금"], 매매["현금W"]], 0.0)
        총 = w * 승자 - 비용률 * 회전
    else:
        회전 = np.select([(앞 == 1) & (w == 1), (앞 == 1) & (w == 0), (앞 == 0) & (w == 1)],
                       [매매["WW"], 매매["WM"], 매매["MW"]], 0.0)
        총 = w * 승자 + (1 - w) * 시장 - 비용률 * 회전
    return 총, 총 - 시장


def 샤프(x):
    return x.mean() / x.std() * np.sqrt(12)


def 보고(이름, w, 승자, 시장, 매매, 구간들, 판정구간):
    원총, 원틸트 = 수익(pd.Series(1.0, index=w.index), 승자, 시장, 매매)
    모총, 모틸트 = 수익(w, 승자, 시장, 매매)
    현총, _ = 수익(w, 승자, 시장, 매매, 현금=True)
    틸트비용전 = 승자 - 시장
    줄들 = []
    for 구간이름, 구간 in 구간들.items():
        e = 검증코드.평가(모틸트, 원틸트, 틸트비용전, w, 구간)
        a, b = 구간
        줄들.append({"시장": 이름, "구간": 구간이름, "개월": e["개월"], "켜진달": e["켜진달"],
                   "틸트_월평균": e["월평균"], "원래틸트_월평균": e["원래_월평균"],
                   "정보비율": e["샤프"], "원래_정보비율": e["원래_샤프"],
                   "틸트_최대낙폭": e["최대낙폭"], "원래틸트_최대낙폭": e["원래_최대낙폭"],
                   "사건합": e["사건합"], "원래_사건합": e["원래_사건합"], "t": e["t"], "결론": e["결론"],
                   "총샤프_모델": 샤프(모총.loc[a:b]), "총샤프_승자": 샤프(원총.loc[a:b]), "총샤프_시장": 샤프(시장.loc[a:b]),
                   "총샤프_현금판": 샤프(현총.loc[a:b]),
                   "총낙폭_모델": 선택코드.낙폭(모총.loc[a:b]).min(), "총낙폭_승자": 선택코드.낙폭(원총.loc[a:b]).min(),
                   "총낙폭_시장": 선택코드.낙폭(시장.loc[a:b]).min(), "총낙폭_현금판": 선택코드.낙폭(현총.loc[a:b]).min()})
    결과 = pd.DataFrame(줄들)
    print(f"\n===== {이름} (판정 구간: {판정구간}) =====")
    with pd.option_context("display.width", 300, "display.max_columns", 40):
        print(결과.drop(columns="시장").to_string(index=False, float_format=lambda x: f"{x:.2f}"))
    사건, _ = 선택코드.사건정의(틸트비용전.loc[구간들[판정구간][0]:구간들[판정구간][1]])
    for a, b in 사건:
        print(f"  틸트 붕괴 {a}부터 {b}까지: 승자 {승자.loc[a:b].mean():.1f}%, 시장 {시장.loc[a:b].mean():.1f}%, "
              f"원래 틸트(비용 후) {선택코드.사건수익(원틸트, [(a, b)])[0]:.1f}%, 모델 {선택코드.사건수익(모틸트, [(a, b)])[0]:.1f}%, "
              f"쉰 달 {int((w.loc[a:b] == 0).sum())}/{len(w.loc[a:b])}")
    return 결과


def 한국():
    회전코드 = 불러오기("회전", "12_회전율계산.py")
    월별코드 = 회전코드.월별코드
    패널 = pd.read_parquet(선택코드.처리폴더 / "월별패널.parquet")
    표 = 회전코드.보유표(패널)
    승표 = 표[표["비중"] > 0]
    새승자 = {m: g.set_index("종목코드")["비중"] for m, g in 승표.groupby("구성연월")}
    변승자 = {m: 회전코드.변한비중(g).clip(lower=0) for m, g in 표.groupby("구성연월")}
    대상 = 월별코드.투자대상표(패널)
    시장비중 = {m: g.set_index("종목코드")[월별코드.시가총액] / g[월별코드.시가총액].sum() for m, g in 대상.groupby("구성연월")}

    월, 회전, 지표, 단독, 보유달 = 검증코드.자료읽기()
    재계산 = (승표["비중"] * 승표["수익률"]).groupby(승표["연월"]).sum()
    차이 = (재계산.reindex(보유달) - 월["롱온리_%"]).abs().max()
    assert 차이 < 1e-9, 차이
    print(f"[한국 확인] 승자 비중 x 수익률 = 롱온리 수익률(최대 차이 {차이:.1e})")
    w, _ = 검증코드.비중만들기(검증코드.신호만들기(지표, 단독, 검증코드.기대최종), 보유달)
    매매 = 매매량들(새승자, 변승자, 시장비중, 보유달)
    print(f"  평균 매매량: 승자 유지 {매매['WW'].mean():.3f}, 승자->시장 {매매['WM'].mean():.3f}, 시장->승자 {매매['MW'].mean():.3f}")
    구간들 = {"선택": 검증코드.선택구간, "검증": 검증코드.검증구간, "2025-12까지": 검증코드.끊은구간}
    전월 = pd.read_parquet(선택코드.처리폴더 / "WML월별수익률.parquet")
    시장 = 전월[전월["방식"] == "2x3"].set_index("연월")["시장_%"].reindex(보유달)
    return 보고("한국", w, 월["롱온리_%"], 시장, 매매, 구간들, "검증")


def 미국():
    미국코드 = 불러오기("미국WML", "24_미국_WML.py")
    최종코드 = 불러오기("미국최종", "25_미국_최종모델.py")
    패널 = 미국코드.패널만들기()
    표 = 미국코드.바구니표(패널)
    승표 = 표[표["비중"] > 0]
    새승자 = {m: g.set_index("permno")["비중"] for m, g in 승표.groupby("구성연월")}
    변승자 = {}
    for m, g in 승표.groupby("구성연월"):
        값 = g["비중"] * (1 + g["수익률"])
        r = 값 / 값.sum()
        r[g["상폐"].values] = 0.0
        변승자[m] = pd.Series(r.values, index=g["permno"].values)
    대상 = 패널[패널["shrcd"].isin([10, 11]) & 패널["exchcd"].isin([1, 2, 3]) & (패널["시총"] > 0)]
    시장비중 = {m: g.set_index("permno")["시총"] / g["시총"].sum() for m, g in 대상.groupby("연월")}

    월, 일, _ = 최종코드.자료읽기()
    지표 = 최종코드.지표만들기(일)
    신호 = 최종코드.신호코드.조합신호(지표, None, 최종코드.최종지표, "점수")
    첫 = str(pd.Period(신호.first_valid_index()) + 1)
    보유달 = list(pd.period_range(첫, 최종코드.끝달, freq="M").astype(str))
    w = pd.Series(1 - 신호.reindex([str(pd.Period(m) - 1) for m in 보유달]).values, index=보유달)
    매매 = 매매량들(새승자, 변승자, 시장비중, 보유달)
    print(f"  [미국] 평균 매매량: 승자 유지 {매매['WW'].mean():.3f}, 승자->시장 {매매['WM'].mean():.3f}, 시장->승자 {매매['MW'].mean():.3f}")
    구간들 = {"전체": (첫, 최종코드.끝달), "2000년 전": (첫, "1999-12"), "2000년부터": ("2000-01", 최종코드.끝달)}
    return 보고("미국", w, 월["롱온리_%"].reindex(보유달), 월["시장_%"].reindex(보유달), 매매, 구간들, "전체")


def 실행():
    선택코드.비용률 = 비용률
    결과 = [한국()]   # 롱온리는 한국만 시험한다(미국은 하지 않음)
    결과폴더.mkdir(parents=True, exist_ok=True)
    pd.concat(결과).to_csv(결과폴더 / "롱온리.csv", index=False, encoding="utf-8-sig")
    print(f"\n[저장] {결과폴더}")


if __name__ == "__main__":
    실행()
