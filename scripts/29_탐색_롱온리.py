# -*- coding: utf-8 -*-
"""
29단계 (탐색, 연구 기록 23절): 롱온리 모멘텀(승자 쪽)에 한국 최종 모델 신호를 붙인다.
신호가 켜지면 다음 달 승자 대신 시장을 든다. 평가는 틸트 수익(승자 - 시장)으로, 15번 평가 함수 그대로.

- 승자 쪽 = 2x3 (소형 승자 + 대형 승자) / 2. 시장 = 투자 대상 시총가중(한국), CRSP vwretd(미국).
- 비용(편도 0.5%): 승자 유지 = sum|새 승자 비중 - 변한 승자 비중|, 승자 -> 시장 = sum|시장 비중 - 변한 승자 비중|,
  시장 -> 승자 = sum|새 승자 비중 - 시장 비중|, 시장 유지 = 0. 참고로 현금으로 바꾸는 경우(승자 <-> 현금 = 1)도 본다.
- 한국: 판정은 검증 기간(2016-01부터 2026-09까지). 미국: 1968-06부터 2024-12까지(참고).

실행: python scripts/29_탐색_롱온리.py   (먼저 15번, 24번, 25번 자료가 있어야 함)
결과: 결과/탐색/롱온리/
"""
import importlib.util
