# -*- coding: utf-8 -*-
"""
19단계 (강건성 4단계): 최종 모델을 5x5, 5분위, 10분위 WML에 적용한다(팀 문서 8.6의 "다른 3가지 방식", B안).
보고용이며 검증 결론은 바꾸지 않는다.

무엇을 하는가 (연구 기록 19.3의 4번)
- 고정: 최종 모델의 지표(시장 변동성 + 모멘텀 변동성), 합치는 방법(겹침 조정 위험 점수), 신호 규칙(60개월, 20%).
- 방식마다 다시 계산: 모멘텀 변동성(그 방식의 일별 WML 126거래일 표준편차), 회전율(그 방식의 실제 종목 비중),
  붕괴 사건(그 방식의 비용 전 원래 WML 하위 5%).
- 방식별 비중: 2x3은 SW, BW +0.5, SL, BL -0.5 / 5x5는 크기1부터 5까지의 모멘텀5 각 +0.2, 모멘텀1 각 -0.2 /
  5분위는 모멘텀5 +1, 모멘텀1 -1 / 10분위는 모멘텀10 +1, 모멘텀1 -1. 바구니 안은 시가총액 비중.
- 확인: 비중 x 수익률의 합이 05번 WML과 같다. 2x3 회전율이 12번 결과와 같다. 2x3 결과가 15번과 같다.

실행: python scripts/19_강건성_방식.py   (먼저 15번까지 실행해 두어야 함)
결과: 결과/강건성/방식.csv
"""
import importlib.util
from pathlib import Path

import numpy as np
import pandas as pd

프로젝트 = Path(__file__).resolve().parent.parent
처리폴더 = 프로젝트 / "처리데이터"
결과폴더 = 프로젝트 / "결과" / "강건성"


def 불러오기(이름, 파일):
    명세 = importlib.util.spec_from_file_location(이름, Path(__file__).resolve().parent / 파일)
    모듈 = importlib.util.module_from_spec(명세)
    명세.loader.exec_module(모듈)
    return 모듈


검증코드 = 불러오기("검증", "15_검증.py")
선택코드, 신호코드 = 검증코드.선택코드, 검증코드.신호코드
회전코드 = 불러오기("회전", "12_회전율계산.py")
월별코드 = 회전코드.월별코드
시가총액 = 월별코드.시가총액
일창 = 126   # 11번과 같은 일별 지표 창

쪽 = {
    "2x3": {"SW": 0.5, "BW": 0.5, "SL": -0.5, "BL": -0.5},
    "5x5": {**{f"크기{a}_모멘텀5": 0.2 for a in range(1, 6)}, **{f"크기{a}_모멘텀1": -0.2 for a in range(1, 6)}},
    "5분위": {"모멘텀5": 1.0, "모멘텀1": -1.0},
    "10분위": {"모멘텀10": 1.0, "모멘텀1": -1.0},
}


class 방식문제(Exception):
    pass


def 확인(조건, 설명):
    if not 조건:
        raise 방식문제(설명)


def 보유표(기본표, 패널, 방식):
    표 = 기본표[기본표[방식].isin(쪽[방식])].copy()
    합 = 표.groupby(["구성연월", 방식])[시가총액].transform("sum")
    표["비중"] = 표[방식].map(쪽[방식]) * 표[시가총액] / 합
    return 표


def 실행():
    패널 = pd.read_parquet(처리폴더 / "월별패널.parquet")
    월전체 = pd.read_parquet(처리폴더 / "WML월별수익률.parquet")
    일전체 = pd.read_parquet(처리폴더 / "일별WML수익률.parquet")
    _, _, 표, 단독, 보유달 = 검증코드.자료읽기()

    # 방식 공통: 투자 대상, 점수, 바구니, 다음 달 수익률, 상폐 여부 (12번과 같은 순서)
    대상 = 월별코드.투자대상표(패널)
    기본 = 대상.merge(월별코드.모멘텀점수(패널), on=["구성연월", "종목코드"], how="inner")
    기본 = 월별코드.다음달수익률붙이기(월별코드.바구니나누기(기본), 패널)
    기본 = 기본[기본["수익률"].notna()].copy()
    상폐 = 패널.set_index(["연월", "종목코드"])["상폐월"]
    기본["상폐"] = 상폐.reindex(pd.MultiIndex.from_arrays([기본["연월"], 기본["종목코드"]])).fillna(False).astype(bool).values

    줄들 = []
    for 방식 in ["2x3", "5x5", "5분위", "10분위"]:
        보 = 보유표(기본, 패널, 방식)
        wml = 월전체[월전체["방식"] == 방식].set_index("연월")["롱숏_%"]
        재 = (보["비중"] * 보["수익률"]).groupby(보["연월"]).sum()
        확인((재 - wml.reindex(재.index)).abs().max() < 1e-9, f"{방식}: 비중으로 계산한 수익률이 05번과 다름")
        회전 = 회전코드.계산(보).set_index("연월")
        확인(np.allclose(회전["구축"], 2.0), f"{방식}: 구축 회전율이 2가 아님")
        if 방식 == "2x3":
            기존 = pd.read_parquet(처리폴더 / "WML회전율.parquet").set_index("연월")
            확인(np.allclose(회전[["리밸런싱", "청산", "구축"]].values, 기존[["리밸런싱", "청산", "구축"]].values), "2x3 회전율이 12번과 다름")
        회전 = 회전.loc[보유달[0]:보유달[-1]]
        전 = wml.loc[보유달[0]:보유달[-1]]

        # 모멘텀 변동성을 이 방식의 일별 WML로 다시 계산하고 신호를 만든다.
        일 = 일전체[일전체["방식"] == 방식].set_index("날짜").sort_index()["롱숏_%"]
        s = 일.rolling(일창, min_periods=일창).std()
        월말 = s.groupby(s.index.to_period("M").astype(str)).last()
        새표 = 표.copy()
        새표["모멘텀변동성"] = 월말.reindex(표.index)
        신호 = 신호코드.위쪽판단(신호코드.위험점수(새표, ["시장변동성", "모멘텀변동성"]), 신호코드.점수창최소)
        if 방식 == "2x3":
            기본신호 = 검증코드.신호만들기(표, 단독, 검증코드.기대최종)
            확인(np.allclose(신호.values, 기본신호.values, equal_nan=True), "2x3 신호가 최종 모델과 다름")
        w, 채움 = 검증코드.비중만들기(신호, 보유달)
        원래 = 선택코드.비용후(pd.Series(1.0, index=보유달), 전, 회전)
        r = 선택코드.비용후(w, 전, 회전)
        for 구간이름, 구간 in (("선택", 검증코드.선택구간), ("검증", 검증코드.검증구간), ("2025-12까지", 검증코드.끊은구간)):
            e = 검증코드.평가(r, 원래, 전, w, 구간)
            if 방식 == "2x3" and 구간이름 == "검증":
                확인(abs(e["t"] - (-1.5311829934)) < 1e-8, "2x3 검증 결과가 15번과 다름")
            줄들.append({"방식": 방식, "구간": 구간이름, "판정": e["결론"], "쉰달": e["켜진달"],
                       "붕괴포착": f"{e['붕괴포착']}/{len(e['_붕괴달'])}",
                       "원래_비용전월평균": 전.loc[구간[0]:구간[1]].mean(), "원래_월평균": e["원래_월평균"], "최종_월평균": e["월평균"],
                       "원래_샤프": e["원래_샤프"], "최종_샤프": e["샤프"], "원래_최대낙폭": e["원래_최대낙폭"],
                       "최종_최대낙폭": e["최대낙폭"], "원래_사건합": e["원래_사건합"], "최종_사건합": e["사건합"],
                       "알파": e["알파"], "t": e["t"], "선택_채운달": 채움["선택"],
                       "월평균회전율": 회전.loc[구간[0]:구간[1], "리밸런싱"].mean()})
        print(f"  {방식}: 확인 통과, 계산 완료")
    표결과 = pd.DataFrame(줄들)
    print("\n[다른 방식] 최종 모델(시장 변동성 + 모멘텀 변동성, 위험 점수), 모멘텀 변동성·회전율·붕괴는 방식별, 비용 0.5%")
    with pd.option_context("display.width", 260):
        print(표결과.to_string(index=False, float_format=lambda x: f"{x:.3f}"))
    결과폴더.mkdir(parents=True, exist_ok=True)
    표결과.to_csv(결과폴더 / "방식.csv", index=False, encoding="utf-8-sig")
    print(f"\n[저장] {결과폴더 / '방식.csv'}")


if __name__ == "__main__":
    실행()
