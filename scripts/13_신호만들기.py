# -*- coding: utf-8 -*-
"""
13단계: 지표로 위험 신호(켜짐 1, 꺼짐 0)를 만든다. 성과는 계산하지 않는다.

왜 필요한가
- t월 말 신호가 t+1월 비중을 정한다(켜지면 0, 꺼지면 1). 14번이 이 신호로 모델을 고른다.

무엇을 하는가 (연구 기록 16.2, 팀 문서 8.3, 8.4)
- 단독 신호: 연속값 지표는 t월을 포함한 최근 60개월(금융난류는 36개부터 60개까지) 중
  t월과 같거나 더 위험한 값(t월 포함)이 창 크기의 20% 이하이면 켠다(동점이 없으면 60개 중 12등 안). 약세장은 누적수익률 < 0, CI는 11번 값.
- 조합 신호(함수, 14번이 부름):
  과반 규칙: 2개는 모두, 3개는 2개 이상, 4개는 3개 이상 켜지면 켠다.
  겹침 조정 위험 점수: z(지표별 t월까지 평균·표준편차, 최소 24개월)를 위험한 쪽이 크게 맞추고 음수를 0으로 자른 z+,
  Σ = t월까지의 상관행렬(최소 24개월), w = Σ^-1 1 (음수는 0), 점수 = w'z+ / sqrt(w'Σw).
  점수가 36개 쌓이면 판단하고 창을 60개까지 늘리며, 상위 20%면 켠다. 판단 전 달은 빈칸(14번이 꺼짐으로 채움).
- 단독 신호 16개를 저장하고, 미래 정보 점검과 손계산 대조를 한다.

하지 않는 일
- 성과 계산, 모델 선택, 지표 정의 고르기.

실행: python scripts/13_신호만들기.py   (먼저 11번을 실행해 두어야 함)
결과: 처리데이터/신호월별.parquet (연월 = 지표 달, 적용연월 = 비중을 정하는 다음 달)
"""
from pathlib import Path

import numpy as np
import pandas as pd

프로젝트 = Path(__file__).resolve().parent.parent
처리폴더 = 프로젝트 / "처리데이터"
저장경로 = 처리폴더 / "신호월별.parquet"

창최대, 난류창최소, 점수창최소 = 60, 36, 36
z최소 = 24
점검달들 = ["2007-10", "2011-07", "2014-03"]

# 연속값 지표: (지표 열, 방향). 방향 +1이면 높을수록, -1이면 낮을수록 위험.
연속 = {
    "모멘텀갭": ("모멘텀갭", 1),
    "시장변동성": ("시장변동성", 1),
    "모멘텀변동성": ("모멘텀변동성", 1),
    "왜도": ("왜도", -1),
    "모멘텀베타": ("모멘텀베타", -1),
    "금융난류": ("금융난류", 1),
    "비유동성_회전율": ("비유동성_회전율", 1),
    "비유동성_Amihud": ("비유동성_Amihud", 1),
    "비유동성갭_회전율": ("비유동성갭_회전율", -1),
    "비유동성갭_Amihud": ("비유동성갭_Amihud", -1),
}
# 약세장: 단독·과반에는 0/1 규칙, 위험 점수에는 누적수익률(낮을수록 위험).
약세장 = {"약세장24": ("약세장누적24", -1), "약세장18": ("약세장누적18", -1)}
규칙형 = ["약세장24", "약세장18", "CI_A", "CI_B", "CI_C", "CI_D"]
단독목록 = list(연속) + 규칙형


class 신호문제(Exception):
    """확인에 실패했을 때 쓰는 오류. 이 오류가 나면 저장하지 않고 멈춘다."""


def 확인(조건, 설명):
    if not 조건:
        raise 신호문제(설명)


def 지표읽기():
    표 = pd.read_parquet(처리폴더 / "지표월별.parquet").set_index("연월")
    달력 = pd.period_range(표.index[0], 표.index[-1], freq="M").astype(str)
    확인(list(표.index) == list(달력), "지표 달에 빠진 달이 있음")
    return 표


def 위쪽판단(값, 창최소):
    """위험한 쪽이 큰 값으로 맞춘 계열. t월 포함 최근 창(창최소부터 60까지)에서 더 큰 값이 20% 미만이면 1."""
    v = 값.values
    결과 = np.full(len(v), np.nan)
    있음 = np.flatnonzero(np.isfinite(v))
    for k, i in enumerate(있음):
        창 = v[있음[max(0, k - 창최대 + 1):k + 1]]
        if len(창) < 창최소:
            continue
        # t월과 같거나 더 위험한 값(t월 포함)이 창의 20% 이하이면 켠다. 동점이 없으면 "더 위험한 값이
        # 20% 미만"과 같고(60개면 12등 안), 위험 점수처럼 0이 많이 겹치는 경우 0인 달이 켜지지 않는다.
        # 20% = 1/5이므로 정수로 비교한다.
        결과[i] = float((창 >= v[i]).sum() * 5 <= len(창))
    return pd.Series(결과, index=값.index)


def 단독신호(표):
    결과 = pd.DataFrame(index=표.index)
    for 이름, (열, 방향) in 연속.items():
        결과[이름] = 위쪽판단(방향 * 표[열], 난류창최소 if 이름 == "금융난류" else 창최대)
    for 이름 in 규칙형:
        결과[이름] = pd.to_numeric(표[이름]).astype(float)
    return 결과


def 점수재료(이름):
    """위험 점수에 쓰는 (지표 열, 방향)."""
    return 약세장[이름] if 이름 in 약세장 else 연속[이름]


def 위험점수(표, 이름들):
    """겹침 조정 위험 점수. t월 값은 t월까지의 자료만 쓴다."""
    x = pd.DataFrame({n: 점수재료(n)[1] * 표[점수재료(n)[0]] for n in 이름들})
    # z: 지표마다 자기 값이 있는 달로 t월까지의 평균·표준편차(최소 24개월)
    평균 = x.expanding(min_periods=z최소).mean()
    표준편차 = x.expanding(min_periods=z최소).std()
    z표 = (x - 평균) / 표준편차
    점수 = pd.Series(np.nan, index=표.index)
    있음 = x.notna().all(axis=1)
    for i, 달 in enumerate(x.index):
        if not (있음.iloc[i] and z표.iloc[i].notna().all()):
            continue
        과거 = x.iloc[:i + 1][있음.iloc[:i + 1]]   # 상관: 모든 지표가 있는 달로 t월까지
        if len(과거) < z최소:
            continue
        zp = z표.iloc[i].clip(lower=0).values
        상관 = 과거.corr().values
        w = np.linalg.solve(상관, np.ones(len(이름들)))
        w = np.clip(w, 0, None)
        점수.iloc[i] = float(w @ zp / np.sqrt(w @ 상관 @ w))
    return 점수


def 조합신호(표, 단독, 이름들, 방법):
    """방법: '과반' 또는 '점수'. 판단할 수 없는 달은 빈칸."""
    if 방법 == "과반":
        s = 단독[list(이름들)]
        필요 = {2: 2, 3: 2, 4: 3}[len(이름들)]
        return (s.sum(axis=1) >= 필요).astype(float).where(s.notna().all(axis=1))
    확인(방법 == "점수", f"알 수 없는 방법: {방법}")
    return 위쪽판단(위험점수(표, 이름들), 점수창최소)


def 미래정보점검(표, 단독):
    print("[미래 정보 점검] 그달 말 이후 지표를 지우고 다시 계산")
    예시조합 = [("모멘텀갭", "시장변동성", "금융난류"), ("왜도", "약세장24", "비유동성갭_회전율", "모멘텀베타")]
    for 달 in 점검달들:
        잘린 = 표.loc[:달]
        다시 = 단독신호(잘린)
        같음 = np.allclose(단독.loc[달].astype(float), 다시.loc[달].astype(float), equal_nan=True)
        확인(같음, f"{달}: 단독 신호가 달라짐")
        for 조합 in 예시조합:
            for 방법 in ("과반", "점수"):
                a = 조합신호(표, 단독, 조합, 방법).loc[달]
                b = 조합신호(잘린, 다시, 조합, 방법).loc[달]
                확인((np.isnan(a) and np.isnan(b)) or a == b, f"{달} {조합} {방법}: 조합 신호가 달라짐")
        print(f"  {달}: 단독 16개와 예시 조합 4개 모두 같음")


def 손계산(표, 단독):
    """2010-06 모멘텀 갭 신호와 2개 지표 위험 점수를 따로 계산한다."""
    달 = "2010-06"
    창 = 표.loc[:달, "모멘텀갭"].dropna().iloc[-60:]
    순위 = (창 > 창.iloc[-1]).sum()
    직접 = float(순위 < 12)
    print(f"\n[손계산 대조] {달} 모멘텀 갭: 창 60개 중 더 큰 값 {순위}개 -> 신호 {직접:.0f}, 코드 {단독.loc[달, '모멘텀갭']:.0f}")
    확인(직접 == 단독.loc[달, "모멘텀갭"], "모멘텀 갭 신호 손계산이 다름")
    # 2개 지표 점수: 식 (z1+ + z2+) / sqrt(2(1+rho)). 두 z가 모두 양수인 달로 확인한다.
    달 = "2008-10"
    a, b = 표.loc[:달, "모멘텀갭"].dropna(), 표.loc[:달, "시장변동성"].dropna()
    za, zb = (a.iloc[-1] - a.mean()) / a.std(), (b.iloc[-1] - b.mean()) / b.std()
    함께 = pd.concat([a, b], axis=1, join="inner")
    rho = 함께.iloc[:, 0].corr(함께.iloc[:, 1])
    직접점수 = (max(za, 0) + max(zb, 0)) / np.sqrt(2 * (1 + rho))
    코드점수 = 위험점수(표, ["모멘텀갭", "시장변동성"]).loc[달]
    print(f"  {달} 갭 + 시장 변동성 위험 점수(z {za:.2f}, {zb:.2f}): 손계산 {직접점수:.10f}, 코드 {코드점수:.10f} (상관 {rho:.3f})")
    확인(np.isclose(직접점수, 코드점수, rtol=1e-10), "위험 점수 손계산이 다름")


def 실행():
    표 = 지표읽기()
    단독 = 단독신호(표)
    확인(set(np.unique(단독.values[np.isfinite(단독.values)])) <= {0.0, 1.0}, "신호에 0, 1 말고 다른 값이 있음")
    # 경계 점검: 창이 60개인 달에 켜진 신호는 더 위험한 값이 11개 이하여야 한다(12등 안).
    for 이름, (열, 방향) in 연속.items():
        if 이름 == "금융난류":
            continue
        값 = 방향 * 표[열]
        for 달 in 단독.index[단독[이름] == 1]:
            창 = 값.loc[:달].dropna().iloc[-창최대:]
            if len(창) == 창최대:
                확인((창 > 창.iloc[-1]).sum() <= 11, f"{이름} {달}: 12등 밖인데 켜짐")
    본기간 = 단독.loc["2005-06":"2026-08"]
    빈 = 본기간.isna().sum()
    확인((빈 == 0).all(), f"지표 달 2005-06부터 빈 신호가 있음: {빈[빈 > 0].to_dict()}")

    손계산(표, 단독)
    미래정보점검(표, 단독)

    print("\n[단독 신호가 처음 나오는 달과 켜짐 비율] (지표 달 2005-06부터 2026-08까지)")
    for c in 단독.columns:
        print(f"  {c}: 처음 {단독[c].first_valid_index()}, 켜짐 비율 {본기간[c].mean() * 100:.1f}%")

    결과 = 단독.copy()
    결과.insert(0, "적용연월", (pd.PeriodIndex(결과.index, freq="M") + 1).astype(str))
    결과.reset_index().to_parquet(저장경로, index=False)
    확인(pd.read_parquet(저장경로).equals(결과.reset_index()), "저장한 파일이 원래 표와 다름")
    print(f"\n[저장] {저장경로.name}: {len(결과)}개월 x 단독 신호 {len(단독.columns)}개")


if __name__ == "__main__":
    실행()
