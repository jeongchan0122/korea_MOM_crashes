# -*- coding: utf-8 -*-
"""
17단계 (강건성 2단계): 최종 모델은 그대로 두고 평가 방식만 바꾼다. 보고용이며 검증 결론은 바꾸지 않는다.

무엇을 하는가 (연구 기록 19.3의 1번, 팀 문서 8.5와 8.6)
- 붕괴 기준 바꾸기: 하위 5%(본 기준), 월 -10% 이하, 하위 10%, 사건 묶음 간격 2개월과 6개월(본 기준 3개월).
  사건 손실 조건만 달라지고 샤프와 낙폭 조건은 같다. 선택·검증 기간 모두 계산한다.
- 위기 구간과 위기 밖 나눠 보기: 선택 기간을 금융위기 구간(2007-07부터 2009-06까지, 결과와 무관한 외부 기준으로
  미리 정함)과 그 밖으로 나눠, 위기 때 얻은 것과 평소에 치른 대가를 함께 본다.
- 2025-12까지 끊은 결과를 함께 표에 넣는다.
- 비용은 본 결과와 같은 편도 0.5%다.

실행: python scripts/17_강건성_평가.py   (먼저 15번까지 실행해 두어야 함)
결과: 결과/강건성/평가_붕괴기준.csv, 평가_위기구간.csv
"""
import importlib.util
from pathlib import Path

import numpy as np
import pandas as pd

프로젝트 = Path(__file__).resolve().parent.parent
결과폴더 = 프로젝트 / "결과" / "강건성"


def 불러오기(이름, 파일):
    명세 = importlib.util.spec_from_file_location(이름, Path(__file__).resolve().parent / 파일)
    모듈 = importlib.util.module_from_spec(명세)
    명세.loader.exec_module(모듈)
    return 모듈


검증코드 = 불러오기("검증", "15_검증.py")
선택코드 = 검증코드.선택코드
위기구간 = ("2007-07", "2009-06")
기준들 = [("하위 5%, 3개월 (본 기준)", "비율", 0.05, 3), ("월 −10% 이하, 3개월", "고정", -10.0, 3),
        ("하위 10%, 3개월", "비율", 0.10, 3), ("하위 5%, 2개월", "비율", 0.05, 2), ("하위 5%, 6개월", "비율", 0.05, 6)]


def 사건정의(전, 방식, 값, 간격):
    """비용 전 원래 WML로 붕괴 달을 정하고, 간격 이내의 붕괴 달끼리 사건으로 묶는다."""
    if 방식 == "비율":
        달들 = sorted(전.nsmallest(int(round(값 * len(전)))).index)
    else:
        달들 = sorted(전.index[전 <= 값])
    사건들 = []
    for 달 in 달들:
        if 사건들 and (pd.Period(달) - pd.Period(사건들[-1][1])).n <= 간격:
            사건들[-1][1] = 달
        else:
            사건들.append([달, 달])
    return [tuple(x) for x in 사건들], 달들


def 성과(r):
    return {"월평균": r.mean(), "샤프": r.mean() / r.std() * np.sqrt(12), "최대낙폭": 선택코드.낙폭(r).min()}


def 실행():
    월, 회전, 표, 단독, 보유달 = 검증코드.자료읽기()
    전 = 월["롱숏_%"]
    원래 = 선택코드.비용후(pd.Series(1.0, index=보유달), 전, 회전)
    w, _ = 검증코드.비중만들기(검증코드.신호만들기(표, 단독, 검증코드.기대최종), 보유달)
    r = 선택코드.비용후(w, 전, 회전)

    # 본 기준이 15번과 같은지 확인
    본 = 검증코드.평가(r, 원래, 전, w, 검증코드.검증구간)
    확인값 = abs(본["t"] - (-1.5311829934)) < 1e-8 and 본["결론"] == "실패"
    if not 확인값:
        raise SystemExit("본 기준 검증 결과가 15번과 다름")

    # 1. 붕괴 기준
    줄들 = []
    for 이름, 방식, 값, 간격 in 기준들:
        for 구간이름, (a, b) in (("선택", 검증코드.선택구간), ("검증", 검증코드.검증구간), ("2025-12까지", 검증코드.끊은구간)):
            사건, 달들 = 사건정의(전.loc[a:b], 방식, 값, 간격)
            원사 = 선택코드.사건수익(원래.loc[a:b], 사건)
            전사 = 선택코드.사건수익(r.loc[a:b], 사건)
            e = 검증코드.평가(r, 원래, 전, w, (a, b))   # 샤프, 낙폭, t는 붕괴 기준과 무관
            사건통과 = sum(전사) > sum(원사) if 사건 else None
            조건 = [e["샤프통과"], e["낙폭통과"], 사건통과 if 사건통과 is not None else True]
            결론 = "실패" if not all(조건) else ("개선" if e["t"] >= 검증코드.유의기준 else "방향만 맞음")
            쉼 = w.loc[a:b] == 0
            줄들.append({"붕괴기준": 이름, "구간": 구간이름, "붕괴달수": len(달들), "사건수": len(사건),
                       "원래_사건합": sum(원사), "최종_사건합": sum(전사), "사건통과": 사건통과,
                       "붕괴포착": int((쉼 & 쉼.index.isin(달들)).sum()), "샤프통과": e["샤프통과"],
                       "낙폭통과": e["낙폭통과"], "t": e["t"], "판정": 결론,
                       "붕괴달": ", ".join(달들) if len(달들) <= 8 else f"{len(달들)}개"})
    붕괴표 = pd.DataFrame(줄들)
    print("[1. 붕괴 기준 바꾸기] 최종 모델, 비용 0.5%. 샤프·낙폭·t는 기준과 무관하고 사건 손실만 달라진다.")
    with pd.option_context("display.width", 250, "display.max_colwidth", 80):
        print(붕괴표.to_string(index=False, float_format=lambda x: f"{x:.2f}"))

    # 2. 위기 구간과 위기 밖 (선택 기간)
    a, b = 검증코드.선택구간
    선택달 = pd.Index(보유달)[(pd.Index(보유달) >= a) & (pd.Index(보유달) <= b)]
    위기 = 선택달[(선택달 >= 위기구간[0]) & (선택달 <= 위기구간[1])]
    밖 = 선택달.difference(위기)
    줄들 = []
    for 이름, 달들 in (("선택 기간 전체", 선택달), ("위기 구간 2007-07부터 2009-06까지", 위기), ("위기 밖", 밖),
                     ("검증 기간 전체", pd.Index(보유달)[pd.Index(보유달) >= 검증코드.검증구간[0]])):
        o, s, ww = 원래.loc[달들], r.loc[달들], w.loc[달들]
        알파, 기울기, t = 선택코드.알파t(s.values, o.values)
        po, ps = 성과(o), 성과(s)
        줄들.append({"구간": 이름, "개월": len(달들), "쉰달": int((ww == 0).sum()),
                   "원래_월평균": po["월평균"], "최종_월평균": ps["월평균"], "차이_월평균": ps["월평균"] - po["월평균"],
                   "원래_샤프": po["샤프"], "최종_샤프": ps["샤프"], "원래_누적": ((1 + o / 100).prod() - 1) * 100,
                   "최종_누적": ((1 + s / 100).prod() - 1) * 100, "알파": float(알파[0]), "t": float(t[0])})
    위기표 = pd.DataFrame(줄들)
    print("\n[2. 위기 구간과 위기 밖 나눠 보기] 최종 모델, 비용 0.5%. 위기 밖은 두 조각을 이어 붙인 102개월이다.")
    with pd.option_context("display.width", 250):
        print(위기표.to_string(index=False, float_format=lambda x: f"{x:.3f}"))
    # 위기 밖에서 쉰 달의 손익: 쉬어서 피한 손실과 놓친 수익
    o, ww = 원래.loc[밖], w.loc[밖]
    쉼 = ww == 0
    print(f"  위기 밖에서 쉰 {int(쉼.sum())}개월: 그 달 원래 WML 합 {o[쉼].sum():.2f}%p "
          f"(피한 손실 {-o[쉼 & (o < 0)].sum():.2f}%p, 놓친 수익 {o[쉼 & (o > 0)].sum():.2f}%p)")
    o, ww = 원래.loc[위기], w.loc[위기]
    쉼 = ww == 0
    print(f"  위기 구간에서 쉰 {int(쉼.sum())}개월: 그 달 원래 WML 합 {o[쉼].sum():.2f}%p "
          f"(피한 손실 {-o[쉼 & (o < 0)].sum():.2f}%p, 놓친 수익 {o[쉼 & (o > 0)].sum():.2f}%p)")

    결과폴더.mkdir(parents=True, exist_ok=True)
    붕괴표.to_csv(결과폴더 / "평가_붕괴기준.csv", index=False, encoding="utf-8-sig")
    위기표.to_csv(결과폴더 / "평가_위기구간.csv", index=False, encoding="utf-8-sig")
    print(f"\n[저장] {결과폴더}")


if __name__ == "__main__":
    실행()
