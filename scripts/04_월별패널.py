# -*- coding: utf-8 -*-
"""
4단계: 02~06번 표와 상폐 수익률을 합쳐 WML 계산에 쓸 월별 패널을 만든다.

왜 필요한가
- WML을 만들려면 종목·월마다 시가총액, 수익률, 시장구분, 거래정지, 관리종목 여부를 한 줄에서 봐야 한다.

무엇을 하는가
- 02~06번을 연월과 종목코드로 합친다.
- 시가총액과 수익률이 모두 없는 줄을 뺀다(상폐 수익률을 넣을 줄은 남긴다).
- 상폐 수익률을 반영연월 줄에 넣어 '수정주가수익률_배당포함_상폐반영_%' 열을 만든다.
- 기존 수익률 열은 그대로 둔다. 모멘텀 점수에는 기존 열, 보유 수익률에는 상폐반영 열을 쓴다.

하지 않는 일
- 종목 필터 적용, 모멘텀 점수 저장, 바구니 나누기, WML 계산, 2026-10 제외, 이전 단계 결과 수정.
- 아래의 투자 대상 조건과 점수는 '빠지는 종목·월'을 세는 확인에만 쓰고 표에 넣지 않는다.

실행: python scripts/04_월별패널.py   (먼저 scripts/03_상폐수익률.py를 실행해 두어야 함)
결과: 처리데이터/월별패널.parquet
"""
from pathlib import Path

import numpy as np
import pandas as pd

프로젝트 = Path(__file__).resolve().parent.parent
처리폴더 = 프로젝트 / "처리데이터"
정리표 = 처리폴더 / "정리표"
저장경로 = 처리폴더 / "월별패널.parquet"

시가총액 = "시가총액_백만원"
수익률 = "수정주가수익률_배당포함_%"
상폐반영 = "수정주가수익률_배당포함_상폐반영_%"

# (정리표 파일 이름, 값 열 이름)
원래표들 = [
    ("02_시가총액", 시가총액),
    ("03_월수익률_배당포함", 수익률),
    ("04_거래정지", "거래정지구분"),
    ("05_관리종목", "관리감리구분"),
    ("06_시장구분", "시장구분"),
]


class 패널문제(Exception):
    """확인에 실패했을 때 쓰는 오류. 이 오류가 나면 저장하지 않고 멈춘다."""


def 확인(조건, 설명):
    if not 조건:
        raise 패널문제(설명)


def 원래표읽기(이름, 값열):
    표 = pd.read_parquet(정리표 / f"{이름}.parquet", columns=["연월", "종목코드", 값열])
    return 표.set_index(["연월", "종목코드"])[값열]


def 패널만들기(원본):
    """원래 표와 상폐 수익률을 합쳐 패널을 만들고, 멈춰야 할 문제를 확인한다."""
    패널 = pd.concat(list(원본.values()), axis=1, join="outer").reset_index()

    상폐 = pd.read_parquet(처리폴더 / "상폐수익률.parquet", columns=["종목코드", "반영연월", "상폐수익률_%"])
    상폐 = 상폐.rename(columns={"반영연월": "연월"})
    패널 = 패널.merge(상폐, on=["연월", "종목코드"], how="outer", validate="one_to_one")
    합친직후 = len(패널)

    # 상폐 수익률을 넣을 달에 월별 수익률이 이미 있으면 어느 값이 맞는지 모르므로 멈춘다.
    겹침 = 패널[수익률].notna() & 패널["상폐수익률_%"].notna()
    확인(not 겹침.any(), f"상폐 수익률을 넣을 달에 월별 수익률이 이미 있음: {int(겹침.sum())}개")

    패널[상폐반영] = 패널[수익률].fillna(패널["상폐수익률_%"])
    패널["상폐월"] = 패널["상폐수익률_%"].notna()
    확인(int(패널["상폐월"].sum()) == len(상폐) == 1270, f"상폐 수익률이 {int(패널['상폐월'].sum())}개만 들어감")

    # 시가총액과 수익률이 모두 없고 상폐 수익률도 없는 줄은 뺀다.
    남김 = 패널[시가총액].notna() | 패널[수익률].notna() | 패널["상폐월"]
    패널 = 패널[남김].drop(columns="상폐수익률_%")

    # 종목명은 29번의 현재 종목명을 쓴다.
    상장 = pd.read_parquet(정리표 / "29_상장일_상폐일.parquet", columns=["종목코드", "종목명"])
    이름표 = 상장.set_index("종목코드")["종목명"]
    패널.insert(2, "종목명", 패널["종목코드"].map(이름표))
    확인(패널["종목명"].notna().all(), "종목명이 없는 줄이 있음")

    순서 = ["연월", "종목코드", "종목명", 시가총액, 수익률, 상폐반영, "상폐월",
          "거래정지구분", "관리감리구분", "시장구분"]
    패널 = 패널[순서].sort_values(["종목코드", "연월"]).reset_index(drop=True)
    확인(not 패널.duplicated(["연월", "종목코드"]).any(), "같은 종목·같은 달이 중복됨")
    print(f"[줄 수] 합친 직후 {합친직후:,}줄 → 빈 줄 제외 후 {len(패널):,}줄")
    return 패널


def 값전체비교(패널, 원본):
    """합친 표의 값을 원래 표와 전부 비교한다."""
    print("\n[값 전체 비교] 열 / 원래 표 값 개수 / 패널 값 개수 / 다른 칸")
    색인표 = 패널.set_index(["연월", "종목코드"])
    for 값열, 원래 in 원본.items():
        현재 = 색인표[값열]
        if 값열 in (시가총액, 수익률):
            확인(int(현재.notna().sum()) == int(원래.notna().sum()), f"{값열}: 값 개수가 달라짐")
        # 패널에 남은 줄 중 원래 표에도 있는 줄만 비교한다(04~06번은 뺀 줄이 있다).
        공통 = 현재.index.intersection(원래.index)
        왼쪽, 오른쪽 = 현재.loc[공통], 원래.loc[공통]
        다름 = ~((왼쪽 == 오른쪽) | (왼쪽.isna() & 오른쪽.isna()))
        확인(not 다름.any(), f"{값열}: 원래 표와 다른 칸 {int(다름.sum())}개")
        print(f"  {값열}: {int(원래.notna().sum()):,} / {int(현재.notna().sum()):,} / 0")

    개수 = int(패널[상폐반영].notna().sum())
    기대 = int(패널[수익률].notna().sum()) + int(패널["상폐월"].sum())
    확인(개수 == 기대, f"상폐반영 값 {개수:,}개, 기대 {기대:,}개")
    print(f"  {상폐반영}: 월별 수익률 {int(패널[수익률].notna().sum()):,} + 상폐 {int(패널['상폐월'].sum()):,} = {개수:,}")


def 시총수익률차이(패널):
    """시가총액과 수익률 중 하나만 있는 줄이 어떤 경우인지 본다."""
    묶음 = 패널[패널[시가총액].notna() | 패널[수익률].notna()]
    시총있음 = 묶음[시가총액].notna()
    수익있음 = 묶음[수익률].notna()
    시총만, 수익만 = 묶음[시총있음 & ~수익있음], 묶음[~시총있음 & 수익있음]
    print(f"\n[시가총액·수익률 차이] 둘 다 있음 {int((시총있음 & 수익있음).sum()):,}줄, "
          f"시가총액만 {len(시총만):,}줄, 수익률만 {len(수익만):,}줄, "
          f"차이 {len(시총만) - len(수익만):,}줄")

    # 그 종목의 첫 달·끝 달인지로 나눈다. 첫 달이면 신규 상장 달일 가능성이 있다.
    첫달 = 묶음.groupby("종목코드")["연월"].transform("min")
    끝달 = 묶음.groupby("종목코드")["연월"].transform("max")
    for 이름, 줄 in [("시가총액만", 시총만), ("수익률만", 수익만)]:
        위치 = np.select([줄["연월"] == 첫달.loc[줄.index], 줄["연월"] == 끝달.loc[줄.index]],
                       ["종목의 첫 달", "종목의 끝 달"], "중간 달")
        print(f"  {이름}: 위치 {pd.Series(위치).value_counts().to_dict()}, "
              f"시장 {줄['시장구분'].value_counts(dropna=False).to_dict()}, "
              f"연월 범위 {줄['연월'].min()} ~ {줄['연월'].max()}")
        print(f"    앞쪽 예시 {줄[['연월', '종목코드', '종목명']].head(4).to_dict('records')}")


def 빠지는종목월(패널):
    """투자 대상 조건을 통과했는데 다음 달 보유 수익률이 없는 종목·월을 분석 기간에서 센다."""
    대상 = (패널["시장구분"].isin(["KS", "KQ"])
          & (패널["거래정지구분"] != "거래정지")
          & (패널["관리감리구분"] != "관리")
          & ~패널["종목명"].str.contains("스팩", na=False)
          & (패널[시가총액] > 0))
    # 구성 시점 1999-12 ~ 2026-08 → 보유 달 2000-01 ~ 2026-09
    표 = 패널[대상 & 패널["연월"].between("1999-12", "2026-08")].copy()

    # 다음 달 보유 수익률을 연월이 정확히 다음 달인 줄에서 찾는다.
    표["다음달"] = (pd.PeriodIndex(표["연월"], freq="M") + 1).astype(str)
    보유 = 패널.set_index(["연월", "종목코드"])[상폐반영]
    키 = pd.MultiIndex.from_arrays([표["다음달"], 표["종목코드"]])
    표["다음달수익률"] = 보유.reindex(키).values

    # 모멘텀 점수(t-11 ~ t-1월 누적, 11개월 모두 필요)가 있는 경우만 따로 센다.
    넓은표 = 패널.pivot(index="연월", columns="종목코드", values=수익률).sort_index()
    점수 = np.log1p(넓은표 / 100).shift(1).rolling(11, min_periods=11).sum()
    점수긴표 = 점수.stack()
    키2 = pd.MultiIndex.from_arrays([표["연월"], 표["종목코드"]])
    표["점수있음"] = 점수긴표.reindex(키2).notna().values

    print("\n[다음 달 수익률이 없어 WML에서 빠지는 종목·월] 구성 1999-12 ~ 2026-08")
    for 이름, 부분 in [("투자 대상 전체", 표), ("그중 모멘텀 점수 있음", 표[표["점수있음"]])]:
        빠짐 = 부분[부분["다음달수익률"].isna()]
        print(f"  {이름}: {len(부분):,}개 중 {len(빠짐):,}개({len(빠짐) / len(부분):.3%}), "
              f"시가총액 합 비중 {빠짐[시가총액].sum() / 부분[시가총액].sum():.3%}, "
              f"종목 {빠짐['종목코드'].nunique()}개")

    빠짐 = 표[표["점수있음"] & 표["다음달수익률"].isna()]
    if len(빠짐):
        끝달 = 패널[패널[상폐반영].notna()].groupby("종목코드")["연월"].max()
        뒤에있음 = 빠짐["다음달"] < 빠짐["종목코드"].map(끝달)
        print(f"  점수 있는 경우의 이유: 이후 수익률이 다시 있음 {int(뒤에있음.sum())}개, "
              f"이후 수익률 없음 {int((~뒤에있음).sum())}개")
        print(f"  예시 {빠짐[['연월', '종목코드', '종목명', 시가총액]].head(12).to_dict('records')}")


def 대표값보기(패널):
    """삼성전자와 상폐 종목의 줄을 눈으로 확인할 수 있게 보여 준다."""
    보기열 = ["연월", "종목코드", "종목명", 시가총액, 수익률, 상폐반영, "상폐월", "시장구분"]
    print("\n[삼성전자 앞 2줄]")
    print(패널[패널["종목코드"] == "A005930"][보기열].head(2).to_string(index=False))
    print("\n[상폐 줄 예시: 표본 5개]")
    print(패널[패널["상폐월"]][보기열].sample(5, random_state=1).to_string(index=False))


def 실행():
    원본 = {값열: 원래표읽기(이름, 값열) for 이름, 값열 in 원래표들}
    패널 = 패널만들기(원본)
    값전체비교(패널, 원본)

    패널.to_parquet(저장경로, index=False)
    다시읽음 = pd.read_parquet(저장경로)
    확인(다시읽음.shape == 패널.shape, "저장 후 크기가 다름")

    시총수익률차이(패널)
    빠지는종목월(패널)
    대표값보기(패널)
    print(f"\n[완료] {패널.shape[0]:,}줄 × {패널.shape[1]}열, 저장: {저장경로}")


if __name__ == "__main__":
    실행()
