# -*- coding: utf-8 -*-
"""
7단계: 일별 수익률 엑셀 3개를 이어 날짜 x 종목 표 하나로 저장한다.

왜 필요한가
- 일별 WML과 일별 시장을 만들 재료다. 엑셀이 커서 한 번만 읽고 parquet로 저장해 둔다.

무엇을 하는가
- 48번(1999-2009), 49번(2010-2019), 47번(2020-2026) 파일을 기간 순서대로 잇는다.
- 항목 코드, 종목 순서, 날짜, 값이 찬 칸 수를 확인하고, 하나라도 다르면 저장하지 않고 멈춘다.

하지 않는 일
- 극단값 처리, 종목 필터, WML 계산. 값은 원본 그대로 저장한다.
- 원본 엑셀 수정. 시가총액과 거래대금 파일은 이번 단계에서 읽지 않는다.

실행: python scripts/07_일별수익률정리.py
결과: 처리데이터/일별수익률.parquet (단위 %, 수정주가수익률 현금배당 포함)
"""
from pathlib import Path

import pandas as pd
from python_calamine import CalamineWorkbook

프로젝트 = Path(__file__).resolve().parent.parent
원본폴더 = 프로젝트 / "한국데이터"
저장경로 = 프로젝트 / "처리데이터" / "일별수익률.parquet"

파일들 = ["48_전종목_일간수익률_1999_2009.xlsx",  # 기간 순서대로 적는다.
       "49_전종목_일간수익률_2010_2019.xlsx",
       "47_전종목_일간수익률_2020_2026.xlsx"]
항목코드 = "S410007900"  # 수정주가수익률(현금배당포함)(%)

# DataGuide 일별 파일의 줄 위치(0부터 셈).
코드줄, 항목코드줄, 집계주기줄, 데이터시작줄 = 8, 11, 13, 14

# 파일을 받을 때 확인한 값. 달라지면 파일이 바뀐 것이므로 멈춘다.
기대거래일, 기대종목수, 기대유효칸 = 6860, 4077, 12_785_268


class 정리문제(Exception):
    """확인에 실패했을 때 쓰는 오류. 이 오류가 나면 저장하지 않고 멈춘다."""


def 확인(조건, 설명):
    if not 조건:
        raise 정리문제(설명)


def 파일읽기(이름):
    """엑셀 하나를 날짜 x 종목 표로 읽고 머리글을 확인한다."""
    시트 = CalamineWorkbook.from_path(str(원본폴더 / 이름)).get_sheet_by_name("Sheet1")
    줄들 = 시트.to_python(skip_empty_area=False)

    코드 = [str(값) for 값 in 줄들[코드줄][1:]]
    확인(len(코드) == len(set(코드)), f"{이름}: 종목 코드가 겹침")
    확인({str(값) for 값 in 줄들[항목코드줄][1:]} == {항목코드}, f"{이름}: 항목 코드가 {항목코드}가 아님")
    확인({str(값) for 값 in 줄들[집계주기줄][1:]} == {"일간"}, f"{이름}: 집계주기가 일간이 아님")

    데이터 = 줄들[데이터시작줄:]
    날짜 = pd.to_datetime([줄[0] for 줄 in 데이터])
    # 빈칸은 글자("")로 읽히므로 숫자로 바꾸면서 결측이 된다.
    표 = pd.DataFrame([줄[1:] for 줄 in 데이터], index=날짜, columns=코드)
    표 = 표.apply(pd.to_numeric, errors="coerce").astype("float64")
    표.index.name = "날짜"
    확인(표.index.is_monotonic_increasing and 표.index.is_unique, f"{이름}: 날짜 순서가 맞지 않거나 겹침")
    print(f"  {이름}: {표.index[0].date()}부터 {표.index[-1].date()}까지, {len(표):,}거래일, 값 {int(표.notna().sum().sum()):,}칸")
    return 표


def 실행():
    print("[파일 읽기]")
    표들 = [파일읽기(이름) for 이름 in 파일들]

    # 세 파일의 종목 순서가 같아야 그대로 이을 수 있다.
    for 표 in 표들[1:]:
        확인(list(표.columns) == list(표들[0].columns), "파일끼리 종목 순서가 다름")
    # 앞 파일의 마지막 날이 뒤 파일의 첫날보다 앞서야 겹치지 않는다.
    for 앞, 뒤 in zip(표들, 표들[1:]):
        확인(앞.index[-1] < 뒤.index[0], "파일끼리 날짜가 겹침")

    전체 = pd.concat(표들)
    유효칸 = int(전체.notna().sum().sum())
    확인(len(전체) == 기대거래일, f"거래일 수가 {기대거래일}이 아님: {len(전체)}")
    확인(전체.shape[1] == 기대종목수, f"종목 수가 {기대종목수}가 아님: {전체.shape[1]}")
    확인(유효칸 == 기대유효칸, f"값이 찬 칸이 {기대유효칸:,}이 아님: {유효칸:,}")

    전체.to_parquet(저장경로)

    # 저장한 파일을 다시 읽어 원본 표와 같은지 확인한다.
    다시 = pd.read_parquet(저장경로)
    확인(다시.equals(전체), "저장한 파일이 원본 표와 다름")

    print(f"\n[저장] {저장경로}")
    print(f"  {len(전체):,}거래일 x {전체.shape[1]:,}종목, 값 {유효칸:,}칸, 다시 읽어 일치 확인")


if __name__ == "__main__":
    실행()
