# -*- coding: utf-8 -*-
"""
3단계: 상폐 종목마다 마지막 달 수익률(상폐 수익률)을 계산한다.

왜 필요한가
- 월 중간에 상폐되면 월말 가격이 없어 그달 수익률이 빈칸이 된다.
- 그대로 두면 상폐 직전의 폭락이 빠진 채 "전달 말 가격에 팔고 나간 것"처럼 계산된다.

계산 규칙
- 기준가 = 월별 수익률이 있는 마지막 달의 말일 이하 마지막 일간 가격
- 마지막가 = 상장폐지일 전날까지의 마지막 일간 가격
- 상폐 수익률(%) = (마지막가 / 기준가 - 1) * 100, 마지막 달의 다음 달에 반영
- 기준가 이후 거래가 없으면 0%
- +300% 초과이거나 기준가가 없으면 가정값(실제 계산값의 그룹 평균)
- 그룹은 마지막 달에 관리종목이거나 거래정지였는지(부실신호)로 나눈다
- 상폐 후 재상장한 종목(상장폐지일 < 현재 상장일)은 일간 주가가 없으므로, 상폐 전 마지막 수익률 달 다음부터
  상장폐지일 전날까지의 일별 수익률을 복리로 합쳐 넣는다. 재상장했어도 그때의 상폐 손실은 실제로 있었기 때문이다.
  이 값은 다른 값과 성격이 달라 가정값 평균에는 넣지 않는다.

하지 않는 일
- 월별 표 합치기, 종목 필터, WML 계산, 원본과 이전 단계 결과 수정.

실행: python scripts/03_상폐수익률.py   (먼저 scripts/02_표정리.py와 scripts/07_일별수익률정리.py를 실행해 두어야 함)
결과: 처리데이터/상폐수익률.parquet
"""
from pathlib import Path

import numpy as np
import pandas as pd

프로젝트 = Path(__file__).resolve().parent.parent
정리표 = 프로젝트 / "처리데이터" / "정리표"
저장경로 = 프로젝트 / "처리데이터" / "상폐수익률.parquet"

앞파일들 = ["40_상폐종목_일간수정주가_1999_2009", "41_상폐종목_일간수정주가_2010_2019",
         "42_상폐종목_일간수정주가_2020_2026"]
보충파일 = "43_누락상폐종목_일간수정주가"
오류기준 = 300  # 이 값(%)을 넘으면 감자 등이 수정주가에 반영되지 않은 오류로 본다.


class 계산문제(Exception):
    """확인에 실패했을 때 쓰는 오류. 이 오류가 나면 저장하지 않고 멈춘다."""


def 확인(조건, 설명):
    if not 조건:
        raise 계산문제(설명)


def 일간읽기(이름):
    return pd.read_parquet(정리표 / f"{이름}.parquet").set_index("날짜")


def 일간주가합치기():
    """40~43번을 날짜 × 종목코드 표 하나로 합치고, 40~42번과 43번의 값 차이를 센다."""
    앞표 = pd.concat([일간읽기(이름) for 이름 in 앞파일들]).sort_index()
    확인(앞표.index.is_unique, "40~42번에 같은 날짜가 겹침")
    보충표 = 일간읽기(보충파일)

    # 양쪽에 모두 있는 종목·날짜의 값이 같은지 센다(멈추지 않고 보고만 함).
    공통종목 = 앞표.columns.intersection(보충표.columns)
    공통날짜 = 앞표.index.intersection(보충표.index)
    왼쪽 = 앞표.loc[공통날짜, 공통종목]
    오른쪽 = 보충표.loc[공통날짜, 공통종목]
    둘다있음 = 왼쪽.notna() & 오른쪽.notna()
    다름 = 둘다있음 & (왼쪽 != 오른쪽)
    print(f"[파일 간 값 비교] 40~42번과 43번의 공통 종목 {len(공통종목)}개, "
          f"둘 다 값이 있는 칸 {int(둘다있음.sum().sum()):,}개, 값이 다른 칸 {int(다름.sum().sum()):,}개, "
          f"값이 다른 종목 {int(다름.any().sum())}개")

    # 같은 종목·날짜가 겹치면 앞 파일(40~42번) 값을 유지한다.
    return 앞표.combine_first(보충표).sort_index()


def 끊긴종목세기(수익률, 상폐코드):
    """첫 달과 마지막 달 사이에 수익률이 빈 달이 있는 종목을 센다."""
    기간 = 수익률.assign(월=pd.PeriodIndex(수익률["연월"], freq="M"))
    묶음 = 기간.groupby("종목코드")["월"]
    빈달 = (묶음.max() - 묶음.min()).map(lambda d: d.n) + 1 - 묶음.size()
    끊김 = 빈달[빈달 > 0].sort_values(ascending=False)
    상폐중 = 끊김[끊김.index.isin(상폐코드)]
    print(f"[수익률 끊김] 전체 {len(끊김)}종목, 그중 상폐 종목 {len(상폐중)}개, "
          f"빈 달이 가장 많은 종목 {끊김.head(8).to_dict()}")


def 실행():
    주가 = 일간주가합치기()

    상장 = pd.read_parquet(정리표 / "29_상장일_상폐일.parquet").set_index("종목코드")
    폐지일 = 상장["상장폐지일_CP10001600"]
    현재상장일 = 상장["상장일_CP10001550"]

    # 상장일이 비어 있는 종목은 재상장 비교를 할 수 없으므로 어떤 경우인지 보여 준다.
    빈상장일 = 상장[현재상장일.isna()]
    print(f"[상장일이 빈 종목] {len(빈상장일)}개, 그중 상장폐지일 있음 {int(빈상장일['상장폐지일_CP10001600'].notna().sum())}개: "
          f"{빈상장일[['종목명', '상장폐지일_CP10001600']].astype(str).to_dict('index')}")

    재상장 = 폐지일 < 현재상장일
    print(f"[상폐 후 재상장] {상장.loc[재상장, '종목명'].to_dict()}")
    대상폐지일 = 폐지일[폐지일.notna() & ~재상장]

    수익률 = pd.read_parquet(정리표 / "03_월수익률_배당포함.parquet")
    마지막달 = 수익률.groupby("종목코드")["연월"].max()
    끊긴종목세기(수익률, set(폐지일.dropna().index))

    정지 = pd.read_parquet(정리표 / "04_거래정지.parquet").set_index(["종목코드", "연월"])["거래정지구분"]
    관리 = pd.read_parquet(정리표 / "05_관리종목.parquet").set_index(["종목코드", "연월"])["관리감리구분"]

    줄들 = []
    수익률없음 = 0
    for 코드, 폐지 in 대상폐지일.items():
        if 코드 not in 마지막달.index:
            수익률없음 += 1  # 월별 수익률이 한 번도 없음(1999-01 이전 상폐 등)
            continue
        끝달 = 마지막달[코드]
        말일 = pd.Period(끝달, "M").end_time.normalize()

        # 상장폐지일 이전 가격만 쓴다(43번은 상폐 뒤 K-OTC 가격이 이어지기 때문).
        가격 = 주가[코드].dropna() if 코드 in 주가.columns else pd.Series(dtype=float)
        가격 = 가격[가격.index < 폐지]
        이전, 이후 = 가격[가격.index <= 말일], 가격[가격.index > 말일]

        부실 = 정지.get((코드, 끝달)) == "거래정지" or 관리.get((코드, 끝달)) == "관리"
        기준가 = 마지막가 = np.nan
        마지막거래일 = pd.NaT
        if len(이전) == 0:
            값, 출처 = np.nan, "가정값(기준가 없음)"
        else:
            기준가 = 이전.iloc[-1]
            확인(기준가 > 0, f"{코드}: 기준가가 0 이하")
            if len(이후) == 0:
                값, 출처, 마지막거래일 = 0.0, "거래없음(0%)", 이전.index[-1]
            else:
                마지막가, 마지막거래일 = 이후.iloc[-1], 이후.index[-1]
                값 = (마지막가 / 기준가 - 1) * 100
                출처 = "실제"
                if 값 > 오류기준:
                    값, 출처 = np.nan, "가정값(오류값)"

        줄들.append({"종목코드": 코드, "종목명": 상장.at[코드, "종목명"], "상장폐지일": 폐지,
                   "마지막수익률월": 끝달, "반영연월": str(pd.Period(끝달, "M") + 1),
                   "마지막거래일": 마지막거래일, "기준가": 기준가, "마지막가": 마지막가,
                   "상폐수익률_%": 값, "부실신호": 부실, "출처": 출처})

    # 재상장 종목: 일간 주가가 없으므로 일별 수익률을 복리로 합친다.
    일별 = pd.read_parquet(프로젝트 / "처리데이터" / "일별수익률.parquet")
    for 코드, 폐지 in 폐지일[재상장].items():
        앞달 = 수익률.loc[(수익률["종목코드"] == 코드) & (수익률["연월"] < 폐지.strftime("%Y-%m")), "연월"]
        확인(len(앞달) > 0, f"{코드}: 상폐 전 월별 수익률이 없음")
        끝달 = 앞달.max()
        값들 = 일별[코드].loc[pd.Period(끝달, "M").end_time:폐지 - pd.Timedelta(days=1)].dropna()
        확인(len(값들) > 0, f"{코드}: 상폐 전 일별 수익률이 없음")
        값 = ((1 + 값들 / 100).prod() - 1) * 100
        부실 = 정지.get((코드, 끝달)) == "거래정지" or 관리.get((코드, 끝달)) == "관리"
        print(f"[재상장 종목의 상폐 수익률] {코드} {상장.at[코드, '종목명']}: 일별 {len(값들)}칸 복리 {값:.1f}%, 반영 {pd.Period(끝달, 'M') + 1}")
        줄들.append({"종목코드": 코드, "종목명": 상장.at[코드, "종목명"], "상장폐지일": 폐지,
                   "마지막수익률월": 끝달, "반영연월": str(pd.Period(끝달, "M") + 1),
                   "마지막거래일": 값들.index[-1], "기준가": np.nan, "마지막가": np.nan,
                   "상폐수익률_%": 값, "부실신호": 부실, "출처": "재상장(일별 복리)"})
    결과 = pd.DataFrame(줄들)

    # 가정값 = 실제 계산값의 그룹 평균(전체 기간). 재상장 값은 넣지 않는다.
    실제 = 결과[결과["출처"] == "실제"]
    확인(실제["상폐수익률_%"].min() >= -100, "상폐 수익률이 -100% 미만임")
    평균 = 실제.groupby("부실신호")["상폐수익률_%"].mean()
    확인(set(평균.index) == {True, False}, "가정값을 낼 그룹이 비어 있음")
    빈칸 = 결과["상폐수익률_%"].isna()
    결과.loc[빈칸, "상폐수익률_%"] = 결과.loc[빈칸, "부실신호"].map(평균)
    확인(결과["상폐수익률_%"].notna().all() and 결과["종목코드"].is_unique, "수익률 빈칸 또는 종목 중복이 있음")

    결과.to_parquet(저장경로, index=False)

    # ---------- 결과 보고 ----------
    값들 = 결과["상폐수익률_%"]
    print(f"\n[종합] 상폐일 있음 {int(폐지일.notna().sum()):,}개, 그중 재상장 {int(재상장.sum())}개, "
          f"월별 수익률 없음 {수익률없음}개 → 계산 {len(결과):,}개")
    print(f"평균 {값들.mean():.1f}%, 중앙값 {값들.median():.1f}%, 최소 {값들.min():.1f}%, 최대 {값들.max():.1f}%")
    print(f"가정값: 부실신호 있음 {평균[True]:.1f}%, 없음 {평균[False]:.1f}%")

    print("\n[출처별] 종목 수 / 부실신호 있음 / 평균(%) / 중앙값(%)")
    for 출처, 묶음 in 결과.groupby("출처"):
        print(f"  {출처}: {len(묶음):,} / {int(묶음['부실신호'].sum()):,} / "
              f"{묶음['상폐수익률_%'].mean():.1f} / {묶음['상폐수익률_%'].median():.1f}")

    기간안 = 결과["반영연월"].between("2000-01", "2026-09")
    print(f"\n[분석 기간 2000-01~2026-09에 반영] {int(기간안.sum()):,}개 "
          f"{결과.loc[기간안, '출처'].value_counts().to_dict()}")
    print(f"[기간 밖] 2000-01 이전 {int((결과['반영연월'] < '2000-01').sum())}개, "
          f"2026-09 이후 {int((결과['반영연월'] > '2026-09').sum())}개")

    # 상폐월보다 뒤까지 월별 수익률이 이어지는 종목
    폐지월 = 결과["상장폐지일"].dt.strftime("%Y-%m")
    늦음 = 결과[결과["마지막수익률월"] > 폐지월]
    print(f"\n[상폐월보다 뒤까지 수익률이 있음] {len(늦음)}개, 출처 {늦음['출처'].value_counts().to_dict()}, "
          f"예 {늦음[['종목명', '상장폐지일', '마지막수익률월']].astype(str).head(5).to_dict('records')}")

    a = 결과[결과["종목코드"] == "A101970"]
    print(f"[A101970] {a[['종목명', '상장폐지일', '마지막수익률월', '출처', '상폐수익률_%']].astype(str).to_dict('records')}")

    # 직접 대조: 합친 표가 아니라 파일별 원래 표에서 기준가와 마지막가를 다시 찾아 비교한다.
    print("\n[직접 대조] 실제 계산 종목 5개")
    원본들 = [일간읽기(이름) for 이름 in 앞파일들 + [보충파일]]
    for _, 줄 in 실제.sample(5, random_state=1).iterrows():
        코드 = 줄["종목코드"]
        가격 = pd.concat([표[코드].dropna() for 표 in 원본들 if 코드 in 표.columns]).sort_index()
        가격 = 가격[~가격.index.duplicated(keep="first")]
        가격 = 가격[가격.index < 줄["상장폐지일"]]
        말일 = pd.Period(줄["마지막수익률월"], "M").end_time.normalize()
        재기준, 재마지막 = 가격[가격.index <= 말일].iloc[-1], 가격.iloc[-1]
        확인(재기준 == 줄["기준가"] and 재마지막 == 줄["마지막가"], f"{코드}: 직접 대조 불일치")
        print(f"  {코드} {줄['종목명']}: 기준가 {재기준:,.0f}({줄['마지막수익률월']}), "
              f"마지막가 {재마지막:,.0f}({str(가격.index[-1].date())}), "
              f"상폐일 {str(줄['상장폐지일'].date())}, 수익률 {줄['상폐수익률_%']:.1f}% -> 일치")

    print(f"\n저장 완료: {저장경로}")


if __name__ == "__main__":
    실행()
