# -*- coding: utf-8 -*-
"""
16단계 (강건성 1단계): 거래비용 가정을 바꾸면 결론이 달라지는지 본다. 보고용이며 검증 결론은 바꾸지 않는다.

무엇을 하는가 (연구 기록 19.2)
- A. 모델 고정형: 최종 모델을 그대로 두고 편도 비용 0%, 0.25%, 0.5%, 1%에서 선택·검증 기간을 다시 평가한다.
- B. 선택 재실행형: 비용 0%, 0.25%, 0.5%, 1%에서 14번의 선택 과정 전체를 다시 돌려 뽑힌 모델을 검증 기간에 적용한다.
  0.5%는 14번과 같은 모델이 뽑히는지 확인하는 용도다.
- 비용별로 시장(무위험수익률을 뺀 값)에 원래 WML을 같은 크기로 더했을 때의 샤프도 낸다.
- 신호는 비용과 무관하므로 그대로 쓰고, 비용률만 14번 함수의 전역값을 바꿔 계산한다.

실행: python scripts/16_강건성_비용.py   (먼저 15번까지 실행해 두어야 함)
결과: 결과/강건성/비용_모델고정.csv, 비용_선택재실행.csv
"""
import importlib.util
from pathlib import Path

import numpy as np
import pandas as pd

프로젝트 = Path(__file__).resolve().parent.parent
처리폴더 = 프로젝트 / "처리데이터"
결과폴더 = 프로젝트 / "결과" / "강건성"


def 불러오기(이름, 파일):
    명세 = importlib.util.spec_from_file_location(이름, Path(__file__).resolve().parent / 파일)
    모듈 = importlib.util.module_from_spec(명세)
    명세.loader.exec_module(모듈)
    return 모듈


# 15번이 불러온 13번, 14번 모듈을 그대로 써야 비용률 변경이 15번 함수에도 적용된다.
검증코드 = 불러오기("검증", "15_검증.py")
선택코드, 신호코드 = 검증코드.선택코드, 검증코드.신호코드
월별코드 = 불러오기("WML계산", "05_WML계산.py")

비용들 = [0.0, 0.25, 0.5, 1.0]
기본비용 = 0.5
기대 = {"선택_t": 3.4049484003259844, "검증_t": -1.5311829934, "최종": 검증코드.기대최종}


class 강건성문제(Exception):
    pass


def 확인(조건, 설명):
    if not 조건:
        raise 강건성문제(설명)


def 시장더하기샤프(원래, 시장초과, 구간):
    a, b = 구간
    w, m = 원래.loc[a:b], 시장초과.loc[a:b]
    샤프 = lambda x: x.mean() / x.std() * np.sqrt(12)
    return 샤프(m), 샤프(m + w), float(w.corr(m))


def 모델고정(월, 회전, 표, 단독, 보유달, 시장초과):
    w, _ = 검증코드.비중만들기(검증코드.신호만들기(표, 단독, 기대["최종"]), 보유달)
    줄들 = []
    for c in 비용들:
        선택코드.비용률 = c
        원래 = 선택코드.비용후(pd.Series(1.0, index=보유달), 월["롱숏_%"], 회전)
        r = 선택코드.비용후(w, 월["롱숏_%"], 회전)
        for 이름, 구간 in (("선택", 검증코드.선택구간), ("검증", 검증코드.검증구간), ("2025-12까지", 검증코드.끊은구간)):
            e = 검증코드.평가(r, 원래, 월["롱숏_%"], w, 구간)
            시장샤프, 더한샤프, 상관 = 시장더하기샤프(원래, 시장초과, 구간)
            줄들.append({"비용_편도%": c, "구간": 이름, "결론": e["결론"],
                       "원래_월평균": e["원래_월평균"], "최종_월평균": e["월평균"],
                       "원래_샤프": e["원래_샤프"], "최종_샤프": e["샤프"],
                       "원래_최대낙폭": e["원래_최대낙폭"], "최종_최대낙폭": e["최대낙폭"],
                       "원래_사건합": e["원래_사건합"], "최종_사건합": e["사건합"], "알파": e["알파"], "t": e["t"],
                       "시장_샤프": 시장샤프, "시장+원래WML_샤프": 더한샤프, "원래WML_시장상관": 상관})
            if c == 기본비용 and 이름 in ("선택", "검증"):
                확인(abs(e["t"] - 기대[f"{이름}_t"]) < 1e-8, f"0.5%의 {이름} t가 기존 결과와 다름: {e['t']}")
    return pd.DataFrame(줄들)


def 선택재실행(월전체, 회전전체, 표전체, 단독전체, 보유달전체):
    줄들 = []
    for c in 비용들:
        선택코드.비용률 = c
        월, 회전, 표, 단독, 보유달 = 선택코드.자료읽기()
        모음 = 선택코드.후보모음(월, 회전, 표, 단독, 보유달)
        고른것, _ = 선택코드.정의고르기(모음)
        재료들 = 선택코드.재료(고른것)
        for m in 재료들 + [고른것["CI"]]:
            모음.추가("단독", [m])
        for 방법 in ("과반", "점수"):
            선택코드.하나씩추가(모음, 재료들, 방법)
        최종, 동률, _ = 선택코드.최종고르기(모음)
        통과 = sum(c2["심사통과"] for c2 in 모음.목록.values())
        if 최종 is None:
            줄들.append({"비용_편도%": c, "뽑힌모델": "없음(통과 심사 0개)", "심사통과수": 통과})
            continue
        이름 = 최종["이름"]
        if c == 기본비용:
            확인(이름 == 기대["최종"], f"0.5%에서 다른 모델이 뽑힘: {이름}")
        w, _ = 검증코드.비중만들기(검증코드.신호만들기(표전체, 단독전체, 이름), 보유달전체)
        원래 = 선택코드.비용후(pd.Series(1.0, index=보유달전체), 월전체["롱숏_%"], 회전전체)
        r = 선택코드.비용후(w, 월전체["롱숏_%"], 회전전체)
        검 = 검증코드.평가(r, 원래, 월전체["롱숏_%"], w, 검증코드.검증구간)
        줄들.append({"비용_편도%": c, "뽑힌모델": 이름, "심사통과수": 통과, "동률수": len(동률),
                   "정의": f"{고른것['약세장']}, {고른것['CI']}, {고른것['비유동성']}",
                   "선택_t": 최종["t"], "선택_샤프": 최종["샤프"], "검증_결론": 검["결론"], "검증_월평균": 검["월평균"],
                   "검증_원래월평균": 검["원래_월평균"], "검증_샤프": 검["샤프"], "검증_원래샤프": 검["원래_샤프"],
                   "검증_t": 검["t"]})
        print(f"  비용 {c}%: {이름} (선택 t {최종['t']:.3f}) -> 검증 {검['결론']}, t {검['t']:.3f}")
    return pd.DataFrame(줄들)


def 실행():
    월, 회전, 표, 단독, 보유달 = 검증코드.자료읽기()
    전체 = pd.read_parquet(처리폴더 / "WML월별수익률.parquet")
    시장 = 전체[전체["방식"] == "2x3"].set_index("연월")["시장_%"].loc[보유달[0]:보유달[-1]]
    시장초과 = 시장 - 월별코드.무위험수익률().reindex(시장.index)

    A = 모델고정(월, 회전, 표, 단독, 보유달, 시장초과)
    print("[A. 모델 고정형] 최종 모델(위험 점수: 시장 변동성 + 모멘텀 변동성), 0.5%는 기존 결과와 같음을 확인")
    with pd.option_context("display.width", 250):
        print(A.to_string(index=False, float_format=lambda x: f"{x:.3f}"))

    print("\n[B. 선택 재실행형] 비용마다 선택을 처음부터 다시 함(보고용)")
    B = 선택재실행(월, 회전, 표, 단독, 보유달)
    with pd.option_context("display.width", 250):
        print(B.to_string(index=False, float_format=lambda x: f"{x:.3f}"))

    선택코드.비용률 = 기본비용
    결과폴더.mkdir(parents=True, exist_ok=True)
    A.to_csv(결과폴더 / "비용_모델고정.csv", index=False, encoding="utf-8-sig")
    B.to_csv(결과폴더 / "비용_선택재실행.csv", index=False, encoding="utf-8-sig")
    print(f"\n[저장] {결과폴더}")


if __name__ == "__main__":
    실행()
