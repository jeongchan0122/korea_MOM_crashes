# -*- coding: utf-8 -*-
"""
21단계 (강건성 6단계): 섞는 지표의 최대 개수를 3개, 5개로 바꿔 모델 고르기를 처음부터 다시 하고(본 기준 4개),
뽑힌 모델을 검증 기간에 적용한다. 가정마다 검증을 다시 보는 것이므로 보고용이며 결론에는 쓰지 않는다(B형).

무엇을 하는가 (연구 기록 19.3의 5번, 팀 문서 8.4)
- 14번의 선택 과정(거르기, 정의 고르기, 하나씩 추가하기, 통과 심사, t 순위, 1 표준오차 규칙)을 그대로 쓰고,
  하나씩 추가하기의 마지막 단계만 바꾼다. 최대 3개면 후보 15 + 15 + 15 = 45개, 5개면 15 + 26 + 26 = 67개.
- 최대 4개로 돌려 14번과 같은 모델이 뽑히는지 먼저 확인한다.

실행: python scripts/21_강건성_선택절차.py   (먼저 15번까지 실행해 두어야 함)
결과: 결과/강건성/선택절차.csv
"""
import importlib.util
from pathlib import Path

import pandas as pd

프로젝트 = Path(__file__).resolve().parent.parent
결과폴더 = 프로젝트 / "결과" / "강건성"


def 불러오기(이름, 파일):
    명세 = importlib.util.spec_from_file_location(이름, Path(__file__).resolve().parent / 파일)
    모듈 = importlib.util.module_from_spec(명세)
    명세.loader.exec_module(모듈)
    return 모듈


검증코드 = 불러오기("검증", "15_검증.py")
선택코드 = 검증코드.선택코드


def 하나씩추가(모음, 재료들, 방법, 최대):
    """14번의 하나씩추가와 같고, 마지막 단계만 최대 개수로 바꾼다."""
    통과 = [c for c in (모음.추가("단독", [m]) for m in 재료들) if c["거르기통과"]]
    if not 통과:
        return
    현재 = max(통과, key=lambda c: c["t"])["지표"]
    for 단계 in range(2, 최대 + 1):
        시험 = [모음.추가(방법, 현재 + [m], 단계=f"{방법}{단계}") for m in 재료들 if m not in 현재]
        통과 = [c for c in 시험 if c["거르기통과"]]
        if not 통과:
            break
        현재 = max(통과, key=lambda c: c["t"])["지표"]


def 실행():
    _, _, 표전체, 단독전체, 보유달 = 검증코드.자료읽기()
    월전체, 회전전체, _, _, _ = 검증코드.자료읽기()
    줄들 = []
    for 최대 in (4, 3, 5):
        월, 회전, 표, 단독, 보유달선택 = 선택코드.자료읽기()
        모음 = 선택코드.후보모음(월, 회전, 표, 단독, 보유달선택)
        고른것, _ = 선택코드.정의고르기(모음)
        재료들 = 선택코드.재료(고른것)
        for m in 재료들 + [고른것["CI"]]:
            모음.추가("단독", [m])
        for 방법 in ("과반", "점수"):
            하나씩추가(모음, 재료들, 방법, 최대)
        최종, 동률, _ = 선택코드.최종고르기(모음)
        이름 = 최종["이름"]
        if 최대 == 4:
            if 이름 != 검증코드.기대최종 or len(모음.목록) != 57:
                raise SystemExit(f"최대 4개에서 14번과 다른 결과: {이름}, 후보 {len(모음.목록)}개")
            print("[확인] 최대 4개: 후보 57개, 14번과 같은 최종 모델")
        w, _ = 검증코드.비중만들기(검증코드.신호만들기(표전체, 단독전체, 이름), 보유달)
        원래 = 선택코드.비용후(pd.Series(1.0, index=보유달), 월전체["롱숏_%"], 회전전체)
        r = 선택코드.비용후(w, 월전체["롱숏_%"], 회전전체)
        검 = 검증코드.평가(r, 원래, 월전체["롱숏_%"], w, 검증코드.검증구간)
        끊 = 검증코드.평가(r, 원래, 월전체["롱숏_%"], w, 검증코드.끊은구간)
        일위 = max(동률, key=lambda c: c["t"])
        줄들.append({"최대지표수": 최대, "후보수": len(모음.목록), "심사통과": sum(c["심사통과"] for c in 모음.목록.values()),
                   "t1위": 일위["이름"], "t1위_t": 일위["t"], "동률수": len(동률), "뽑힌모델": 이름, "선택_t": 최종["t"],
                   "검증_판정": 검["결론"], "검증_샤프": 검["샤프"], "검증_원래샤프": 검["원래_샤프"], "검증_t": 검["t"],
                   "끊은_판정": 끊["결론"], "끊은_t": 끊["t"]})
        print(f"  최대 {최대}개: 후보 {len(모음.목록)}개, 뽑힌 모델 {이름} (선택 t {최종['t']:.3f}) -> 검증 {검['결론']}")
    표결과 = pd.DataFrame(줄들)
    with pd.option_context("display.width", 260, "display.max_colwidth", 60):
        print(표결과.to_string(index=False, float_format=lambda x: f"{x:.3f}"))
    결과폴더.mkdir(parents=True, exist_ok=True)
    표결과.to_csv(결과폴더 / "선택절차.csv", index=False, encoding="utf-8-sig")
    print(f"\n[저장] {결과폴더 / '선택절차.csv'}")


if __name__ == "__main__":
    실행()
