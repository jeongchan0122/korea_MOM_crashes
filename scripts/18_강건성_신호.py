# -*- coding: utf-8 -*-
"""
18단계 (강건성 3단계): 최종 모델의 지표는 그대로 두고 신호 규칙만 바꾼다. 보고용이며 검증 결론은 바꾸지 않는다.

무엇을 하는가 (연구 기록 19.3의 2번, 팀 문서 8.3과 8.6)
- 판단 창: 위험 점수를 최근 몇 개월과 비교하나. 36개월, 120개월(본 기준 60개월, 판단 시작은 36개부터).
- 켜지는 기준: 위험한 쪽 10%, 30%(본 기준 20%).
- 시장 변동성 창: 일별 시장 수익률 252거래일(약 12개월, Wang & Xu 2015)로 계산(본 기준 126거래일).
- 각 변형의 신호로 비중을 만들고, 선택·검증·2025-12까지를 15번의 평가 함수로 다시 계산한다. 비용은 0.5%.

실행: python scripts/18_강건성_신호.py   (먼저 15번까지 실행해 두어야 함)
결과: 결과/강건성/신호변형.csv
"""
import importlib.util
from pathlib import Path

import numpy as np
import pandas as pd

프로젝트 = Path(__file__).resolve().parent.parent
처리폴더 = 프로젝트 / "처리데이터"
결과폴더 = 프로젝트 / "결과" / "강건성"


def 불러오기(이름, 파일):
    명세 = importlib.util.spec_from_file_location(이름, Path(__file__).resolve().parent / 파일)
    모듈 = importlib.util.module_from_spec(명세)
    명세.loader.exec_module(모듈)
    return 모듈


검증코드 = 불러오기("검증", "15_검증.py")
선택코드, 신호코드 = 검증코드.선택코드, 검증코드.신호코드
지표들 = ("시장변동성", "모멘텀변동성")


def 시장변동성252(표):
    일 = pd.read_parquet(처리폴더 / "일별WML수익률.parquet")
    m = 일[일["방식"] == "2x3"].set_index("날짜").sort_index()["시장_%"]
    s = m.rolling(252, min_periods=252).std()
    월말 = s.groupby(s.index.to_period("M").astype(str)).last()
    새 = 표.copy()
    새["시장변동성"] = 월말.reindex(표.index)
    return 새


def 신호(표, 창최대=60, 위쪽=20):
    기존 = (신호코드.창최대, 신호코드.위쪽퍼센트)
    신호코드.창최대, 신호코드.위쪽퍼센트 = 창최대, 위쪽
    try:
        return 신호코드.위쪽판단(신호코드.위험점수(표, list(지표들)), 신호코드.점수창최소)
    finally:
        신호코드.창최대, 신호코드.위쪽퍼센트 = 기존


def 실행():
    월, 회전, 표, 단독, 보유달 = 검증코드.자료읽기()
    전 = 월["롱숏_%"]
    원래 = 선택코드.비용후(pd.Series(1.0, index=보유달), 전, 회전)
    변형들 = [("본 기준 (60개월, 20%, 126일)", 표, 60, 20), ("판단 창 36개월", 표, 36, 20), ("판단 창 120개월", 표, 120, 20),
            ("위험한 쪽 10%", 표, 60, 10), ("위험한 쪽 30%", 표, 60, 30), ("시장 변동성 252일", 시장변동성252(표), 60, 20)]
    기본신호 = 검증코드.신호만들기(표, 단독, 검증코드.기대최종)
    줄들 = []
    for 이름, 쓸표, 창, 위쪽 in 변형들:
        s = 신호(쓸표, 창, 위쪽)
        if 이름.startswith("본 기준"):
            같음 = np.allclose(s.values, 기본신호.values, equal_nan=True)
            if not 같음:
                raise SystemExit("본 기준 신호가 최종 모델 신호와 다름")
        w, 채움 = 검증코드.비중만들기(s, 보유달)
        r = 선택코드.비용후(w, 전, 회전)
        for 구간이름, 구간 in (("선택", 검증코드.선택구간), ("검증", 검증코드.검증구간), ("2025-12까지", 검증코드.끊은구간)):
            e = 검증코드.평가(r, 원래, 전, w, 구간)
            줄들.append({"변형": 이름, "구간": 구간이름, "판정": e["결론"], "쉰달": e["켜진달"], "개월": e["개월"],
                       "붕괴포착": f"{e['붕괴포착']}/{len(e['_붕괴달'])}", "원래_샤프": e["원래_샤프"], "최종_샤프": e["샤프"],
                       "원래_최대낙폭": e["원래_최대낙폭"], "최종_최대낙폭": e["최대낙폭"],
                       "원래_사건합": e["원래_사건합"], "최종_사건합": e["사건합"], "알파": e["알파"], "t": e["t"],
                       "채운달": 채움["선택"] if 구간이름 == "선택" else 채움["검증"]})
        print(f"  {이름}: 완료")
    표결과 = pd.DataFrame(줄들)
    print("\n[신호 변형] 최종 모델의 지표(시장 변동성 + 모멘텀 변동성), 위험 점수, 비용 0.5%")
    with pd.option_context("display.width", 250):
        print(표결과.to_string(index=False, float_format=lambda x: f"{x:.3f}"))
    결과폴더.mkdir(parents=True, exist_ok=True)
    표결과.to_csv(결과폴더 / "신호변형.csv", index=False, encoding="utf-8-sig")
    print(f"\n[저장] {결과폴더 / '신호변형.csv'}")


if __name__ == "__main__":
    실행()
