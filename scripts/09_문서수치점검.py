def 시총보정점검(패널, 점수):
    """비율 = (이번 달 시총 ÷ 전달 시총) ÷ (1 + 월 수익률)이 0.67 미만이면 사건으로 보고,
    6개월 안에 누적 비율이 0.8과 1.25 사이로 돌아오면 일시적 과소로 보고 보정한다."""
    시총 = 패널.pivot(index="연월", columns="종목코드", values=시가총액).sort_index()
    수익 = 패널.pivot(index="연월", columns="종목코드", values=수익률).sort_index().reindex_like(시총)
    비율 = (시총 / 시총.shift(1)) / (1 + 수익 / 100)
    보정 = 시총.copy()
    바뀐칸 = 0
    for 코드 in 시총.columns:
        값 = 비율[코드].values
        for i in np.where(값 < 0.67)[0]:
            누적 = 1.0
            for j in range(i, min(i + 7, len(값))):
                if not np.isfinite(값[j]):
                    break
                누적 *= 값[j]
                if j > i and 0.8 <= 누적 <= 1.25:
                    기준 = 보정[코드].iloc[i - 1]
                    for k in range(i, j):
                        기준 *= 1 + 수익[코드].iloc[k] / 100
                        보정.iloc[k, 보정.columns.get_loc(코드)] = 기준
                        바뀐칸 += 1
                    break
    새패널 = 패널.copy()
    새값 = 보정.stack().rename("새시총")
    새패널[시가총액] = pd.MultiIndex.from_arrays([새패널["연월"], 새패널["종목코드"]]).map(새값.to_dict())
    새대상 = 월별코드.투자대상표(새패널)
    전대상 = 월별코드.투자대상표(패널)
    print(f"\n[8. 시가총액 보정] 바뀐 칸 {바뀐칸:,}개, 투자 대상 대비 {바뀐칸 / len(전대상) * 100:.2f}%")
    for 방식 in 방식들:
        전 = WML(나눠서계산(전대상, 점수, 패널), 방식)["롱숏_%"]
        후 = WML(나눠서계산(새대상, 점수, 패널), 방식)["롱숏_%"]
        print(f"  {방식}: 월평균 {전.mean():.3f} → {후.mean():.3f}, 최악의 달 5개 같음 {set(전.nsmallest(5).index) == set(후.nsmallest(5).index)}")


def 거래없음점검(상폐, 표):
    없음 = 상폐[(상폐["출처"] == "거래없음(0%)") & 상폐["반영연월"].between("2000-01", "2026-09")]
    합 = 표.merge(없음[["종목코드", "반영연월"]], left_on=["종목코드", "연월"], right_on=["종목코드", "반영연월"])
    print(f"\n[9. 거래 없음(0%)] 분석 기간 {len(없음)}개, 바구니에 들어간 종목 {len(합)}개. 이 종목들을 −100%로 바꾼 결과")
    바꾼표 = 표.copy()
    키 = set(zip(없음["종목코드"], 없음["반영연월"]))
    표시 = [(c, m) in 키 for c, m in zip(바꾼표["종목코드"], 바꾼표["연월"])]
    바꾼표.loc[표시, "수익률"] = -100.0
    이름들 = {"2x3": (["SW", "BW"], ["SL", "BL"]), "5x5": ([f"크기{a}_모멘텀5" for a in range(1, 6)], [f"크기{a}_모멘텀1" for a in range(1, 6)]),
           "5분위": (["모멘텀5"], ["모멘텀1"]), "10분위": (["모멘텀10"], ["모멘텀1"])}
    for 방식 in 방식들:
        전, 후 = WML(표, 방식)["롱숏_%"], WML(바꾼표, 방식)["롱숏_%"]
        d = 후 - 전
        승, 패 = 이름들[방식]
        print(f"  {방식}: 승자 쪽 {int(합[방식].isin(승).sum())}개, 패자 쪽 {int(합[방식].isin(패).sum())}개, 월평균 변화 {d.mean():+.4f}%p, 가장 큰 달 {d.loc[d.abs().idxmax()]:+.3f}%p")


