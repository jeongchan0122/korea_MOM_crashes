def 상폐점수점검(패널, 대상, 점수):
    넓은표 = 패널.pivot(index="연월", columns="종목코드", values=상폐반영).sort_index()
    다른점수 = (np.expm1(np.log1p(넓은표 / 100).shift(1).rolling(11, min_periods=11).sum()) * 100)
    다른점수 = 다른점수.stack().rename("다른점수").rename_axis(["구성연월", "종목코드"]).reset_index()
    합 = 대상.merge(점수, on=["구성연월", "종목코드"], how="left").merge(다른점수, on=["구성연월", "종목코드"], how="left")
    둘다 = 합["점수"].notna() & 합["다른점수"].notna()
    print(f"\n[2. 점수에 상폐반영 수익률 사용] 점수 {int(합['점수'].notna().sum()):,}개, 값 다름 "
          f"{int((합.loc[둘다, '점수'] - 합.loc[둘다, '다른점수']).abs().gt(1e-9).sum())}개, "
          f"점수가 새로 생김 {int((합['점수'].isna() & 합['다른점수'].notna()).sum())}개, 사라짐 {int((합['점수'].notna() & 합['다른점수'].isna()).sum())}개")


