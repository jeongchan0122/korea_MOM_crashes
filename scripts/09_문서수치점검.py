def 크기균형시장(대상, 패널, 월별):
    시장표 = 월별코드.다음달수익률붙이기(대상, 패널)
    시장표 = 시장표[시장표["수익률"].notna()]
    중앙값 = 대상[대상["시장구분"] == "KS"].groupby("구성연월")[시가총액].median()
    시장표 = 시장표.assign(크기=np.where(시장표[시가총액] <= 시장표["구성연월"].map(중앙값), "S", "B"))
    비중 = 시장표.groupby(["구성연월", "크기"])[시가총액].sum().unstack()
    소형비중 = 비중["S"] / 비중.sum(axis=1) * 100
    print(f"\n[5. 크기 균형 시장] 시장 안 소형 쪽의 시총 비중 평균 {소형비중.mean():.1f}%, 최소 {소형비중.min():.1f}%, 최대 {소형비중.max():.1f}%, 끝 {소형비중.iloc[-1]:.1f}%")
    크기별 = 시장표.groupby(["연월", "크기"]).apply(월별코드.가중평균, include_groups=False).unstack()
    균형 = (크기별["S"] + 크기별["B"]) / 2
    for 방식 in ["2x3", "5x5"]:
        d = 월별[월별["방식"] == 방식].set_index("연월")
        for 시작, 끝 in [("2000-01", "2026-09"), ("2013-01", "2026-09")]:
            z = d.loc[시작:끝]
            차1, 차2 = z["롱온리_%"] - z["시장_%"], z["롱온리_%"] - 균형.reindex(z.index)
            print(f"  {방식} {시작}부터 {끝}까지: 승자 - 시장 {차1.mean():.2f} (NW {NW(차1):.2f}), 승자 - 크기 균형 시장 {차2.mean():.2f} (NW {NW(차2):.2f})")


def 구간과집중도(대상, 점수, 패널, 표):
    기본 = WML(표)["롱숏_%"]
    뺀표 = 나눠서계산(대상[~대상["종목코드"].isin(두종목)], 점수, 패널)
    뺌 = WML(뺀표)["롱숏_%"]
    print("\n[6. 구간별 2x3] 구간 / 기본 월평균 (NW t) / 최악 / 두 종목 제외 월평균 (NW t) / 최악")
    for 시작, 끝 in [("2000-01", "2026-09"), ("2005-07", "2015-12"), ("2016-01", "2026-09"), ("2016-01", "2025-12")]:
        a, b = 기본.loc[시작:끝], 뺌.loc[시작:끝]
        print(f"  {시작}부터 {끝}까지: {a.mean():.2f} ({NW(a):.2f}) / {a.min():.1f} ({a.idxmin()}) / {b.mean():.2f} ({NW(b):.2f}) / {b.min():.1f}")
    for 시작, 끝 in [("2005-07", "2015-12"), ("2016-01", "2026-09")]:
        a = 기본.loc[시작:끝]
        n = int(round(len(a) * 0.05))
        print(f"  {시작}부터 {끝}까지의 하위 5% {n}개 달: {[(k, round(v, 1)) for k, v in a.nsmallest(n).items()]}")
