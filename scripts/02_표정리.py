class 정리문제(Exception):
    """확인에 실패했을 때 쓰는 오류. 이 오류가 나면 저장하지 않고 멈춘다."""


def 확인(조건, 설명):
    """조건이 거짓이면 설명을 담아 멈춘다."""
    if not 조건:
        raise 정리문제(설명)


def 복사본읽기(이름):
    return pd.read_parquet(복사본폴더 / f"{이름}__Sheet1.parquet")


def 행찾기(표, 글자):
    """A열(c0)에서 글자와 똑같은 칸의 행 위치를 찾는다. 행 번호를 고정하지 않는 이유는
    파일마다 머리글 줄 수가 다를 수 있기 때문이다."""
    위치 = 표.index[표["c0"] == 글자]
    확인(len(위치) == 1, f"A열의 '{글자}' 칸이 {len(위치)}개임(1개여야 함)")
    return 위치[0]


def 머리글과데이터(표):
    """달력형 복사본을 머리글(열별 코드·이름·아이템)과 데이터(날짜 줄)로 나눈다."""
    머리글 = pd.DataFrame({
        "코드": 표.loc[행찾기(표, "코드")].iloc[1:],
        "코드명": 표.loc[행찾기(표, "코드명")].iloc[1:],
        "아이템명": 표.loc[행찾기(표, "아이템명")].iloc[1:],
    })
    머리글 = 머리글[머리글["코드"].notna()]  # 코드가 없는 열은 데이터 열이 아니다.
    데이터줄 = 표["c0"].fillna("").str.match(날짜형식)
    날짜 = pd.to_datetime(표.loc[데이터줄, "c0"].str[:10], format="%Y-%m-%d")
    데이터 = 표.loc[데이터줄, 머리글.index]
    return 머리글, 데이터, 날짜


def 숫자로(값들, 이름):
    """글자를 숫자로 바꾼다. 빈칸은 그대로 두고, 못 바꾸는 값이 있으면 멈춘다."""
    숫자 = pd.to_numeric(값들, errors="coerce")
    못바꿈 = 값들.notna() & 숫자.isna()
    확인(not 못바꿈.any(), f"{이름}: 숫자로 못 바꾸는 값 {int(못바꿈.sum())}개, "
                        f"예 {값들[못바꿈].unique()[:5].tolist()}")
    확인(np.isfinite(숫자.dropna()).all(), f"{이름}: 무한대 값이 있음")
    return 숫자


def 저장(표, 이름):
    """저장한 뒤 다시 읽어 표 크기가 같은지 확인한다."""
    경로 = 저장폴더 / f"{이름}.parquet"
    표.to_parquet(경로, index=False)
    다시읽음 = pd.read_parquet(경로)
    확인(다시읽음.shape == 표.shape, f"{이름}: 저장 후 크기가 다름")
    return 표


def 월별정리(이름, 아이템명, 값열, 숫자변환):
    """월별 종목 파일을 '종목·월마다 한 줄' 표로 바꾼다. 값이 빈 칸의 줄은 만들지 않는다."""
    머리글, 데이터, 날짜 = 머리글과데이터(복사본읽기(이름))
    확인(set(머리글["아이템명"]) == {아이템명}, f"{이름}: 아이템명이 예상과 다름 {set(머리글['아이템명'])}")
    확인(len(머리글) == 4076 and 머리글["코드"].is_unique, f"{이름}: 종목 수가 4,076개가 아니거나 코드가 중복됨")
    확인(len(날짜) == 334 and 날짜.is_unique, f"{이름}: 날짜가 334개가 아니거나 중복됨")
    찬칸 = int(데이터.notna().sum().sum())

    # 날짜를 연월 글자로 바꾸고, 넓은 표를 '한 칸 = 한 줄'로 편다.
    데이터 = 데이터.copy()
    데이터.insert(0, "연월", 날짜.dt.strftime("%Y-%m").values)
    긴표 = 데이터.melt(id_vars="연월", var_name="열", value_name=값열)
    긴표 = 긴표[긴표[값열].notna()]
    긴표["종목코드"] = 긴표["열"].map(머리글["코드"])
    긴표["종목명"] = 긴표["열"].map(머리글["코드명"])
    if 숫자변환:
        긴표[값열] = 숫자로(긴표[값열], 이름)
    긴표 = (긴표[["연월", "종목코드", "종목명", 값열]]
          .sort_values(["종목코드", "연월"]).reset_index(drop=True))

    확인(len(긴표) == 찬칸, f"{이름}: 값이 찬 칸 {찬칸:,}개인데 줄 수는 {len(긴표):,}개")
    확인(not 긴표.duplicated(["연월", "종목코드"]).any(), f"{이름}: 같은 종목·같은 달이 중복됨")
    확인(긴표["연월"].min() == "1999-01" and 긴표["연월"].max() == "2026-10", f"{이름}: 기간이 예상과 다름")
    return 저장(긴표, 이름), 찬칸


def 날짜별정리(이름, 열수, 날짜수, 첫날, 끝날, 연월포함):
    """일간 주가와 지수 파일을 '날짜마다 한 줄, 코드는 열' 표로 바꾼다."""
    머리글, 데이터, 날짜 = 머리글과데이터(복사본읽기(이름))
    확인(len(머리글) == 열수 and 머리글["코드"].is_unique, f"{이름}: 코드 수가 {열수}개가 아니거나 코드가 중복됨")
    확인(len(날짜) == 날짜수 and 날짜.is_unique, f"{이름}: 날짜가 {날짜수}개가 아니거나 중복됨")
    확인(str(날짜.iloc[0].date()) == 첫날 and str(날짜.iloc[-1].date()) == 끝날, f"{이름}: 기간이 예상과 다름")
    찬칸 = int(데이터.notna().sum().sum())

    숫자표 = pd.DataFrame({머리글.at[열, "코드"]: 숫자로(데이터[열], f"{이름} {머리글.at[열, '코드']}")
                        for 열 in 데이터.columns})
    확인(int(숫자표.notna().sum().sum()) == 찬칸, f"{이름}: 값이 찬 칸 수가 달라짐")
    숫자표.insert(0, "날짜", 날짜.values)
    if 연월포함:
        숫자표.insert(0, "연월", 날짜.dt.strftime("%Y-%m").values)
    return 저장(숫자표.reset_index(drop=True), 이름), 찬칸


